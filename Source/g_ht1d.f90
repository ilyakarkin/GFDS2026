        SUBROUTINE HT1D_REBUILD_GPU(NM)
            INTEGER, INTENT(IN) :: NM
            INTEGER :: IW,LINE,NW
            REAL(EB), ALLOCATABLE :: A_H(:)
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            GM => GPU_MESHES(NM)
            IF (.NOT.ALLOCATED(HT1D_SAVED)) ALLOCATE(HT1D_SAVED(NMESHES))
            NW = MESHES(NM)%N_EXTERNAL_WALL_CELLS+MESHES(NM)%N_INTERNAL_WALL_CELLS
            IF (ALLOCATED(HT1D_SAVED(NM)%VALID)) DEALLOCATE(HT1D_SAVED(NM)%VALID,HT1D_SAVED(NM)%VALUES)
            ALLOCATE(HT1D_SAVED(NM)%VALID(1:MAX(1,NW)),HT1D_SAVED(NM)%VALUES(1:MAX(1,NW),1:4))
            HT1D_SAVED(NM)%VALID = .FALSE.
            HT1D_SAVED(NM)%VALUES = 0._EB

            IF (GM%HT1D_INITIALIZED .AND. GM%HT1D_N_LINES>0 .AND. ALLOCATED(GM%HT1D_WALL_TO_LINE_H)) THEN
                CALL GPU_WAIT(GM%STRM)
                ALLOCATE(A_H(1:GM%HT1D_N_LINES))
                ! Only the lines with an EXPOSED backside on another mesh keep values between steps (received by the
                ! end-of-step exchange); all others are reloaded by HT1D_LOAD_BOUNDARY_GPU.
                DO IW=1,MIN(NW,SIZE(GM%HT1D_WALL_TO_LINE_H))
                    LINE = GM%HT1D_WALL_TO_LINE_H(IW)
                    IF (LINE<1 .OR. LINE>GM%HT1D_N_LINES) CYCLE
                    IF (GM%HT1D_BACK_REMOTE_H(LINE)/=0 .AND. GM%HT1D_BACKING_H(LINE)==EXPOSED) &
                        HT1D_SAVED(NM)%VALID(IW) = .TRUE.
                ENDDO
                A_H = GM%HT1D_TMP_G_B_D     ; CALL SAVE_LINE_VALUES(1)
                A_H = GM%HT1D_HTCB_D        ; CALL SAVE_LINE_VALUES(2)
                A_H = GM%HT1D_Q_RAD_IN_B_D  ; CALL SAVE_LINE_VALUES(3)
                A_H = GM%HT1D_EMISSIVITY_B_D; CALL SAVE_LINE_VALUES(4)
                DEALLOCATE(A_H)
            ENDIF

            CALL RELEASE_GPU_HT1D(NM)
            CALL INITIALIZE_GPU_HT1D(NM)

            CONTAINS

            SUBROUTINE SAVE_LINE_VALUES(IV)
                INTEGER, INTENT(IN) :: IV
                DO IW=1,MIN(NW,SIZE(GM%HT1D_WALL_TO_LINE_H))
                    LINE = GM%HT1D_WALL_TO_LINE_H(IW)
                    IF (LINE<1 .OR. LINE>GM%HT1D_N_LINES) CYCLE
                    HT1D_SAVED(NM)%VALUES(IW,IV) = A_H(LINE)
                ENDDO
            END SUBROUTINE SAVE_LINE_VALUES

        END SUBROUTINE HT1D_REBUILD_GPU

        SUBROUTINE HT1D_RESTORE_BACKSIDE_GPU(NM)
            INTEGER, INTENT(IN) :: NM
            INTEGER :: IW,LINE
            REAL(EB), ALLOCATABLE :: A_H(:)
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            GM => GPU_MESHES(NM)
            IF (.NOT.ALLOCATED(HT1D_SAVED)) RETURN
            IF (.NOT.ALLOCATED(HT1D_SAVED(NM)%VALID)) RETURN
            IF (GM%HT1D_INITIALIZED .AND. GM%HT1D_N_LINES>0 .AND. ALLOCATED(GM%HT1D_WALL_TO_LINE_H)) THEN
                CALL GPU_WAIT(GM%STRM)
                ALLOCATE(A_H(1:GM%HT1D_N_LINES))
                A_H = GM%HT1D_TMP_G_B_D     ; CALL RESTORE_LINE_VALUES(1) ; GM%HT1D_TMP_G_B_D      = A_H
                A_H = GM%HT1D_HTCB_D        ; CALL RESTORE_LINE_VALUES(2) ; GM%HT1D_HTCB_D         = A_H
                A_H = GM%HT1D_Q_RAD_IN_B_D  ; CALL RESTORE_LINE_VALUES(3) ; GM%HT1D_Q_RAD_IN_B_D   = A_H
                A_H = GM%HT1D_EMISSIVITY_B_D; CALL RESTORE_LINE_VALUES(4) ; GM%HT1D_EMISSIVITY_B_D = A_H
                DEALLOCATE(A_H)
            ENDIF
            DEALLOCATE(HT1D_SAVED(NM)%VALID,HT1D_SAVED(NM)%VALUES)

            CONTAINS

            SUBROUTINE RESTORE_LINE_VALUES(IV)
                INTEGER, INTENT(IN) :: IV
                DO IW=1,MIN(SIZE(HT1D_SAVED(NM)%VALID),SIZE(GM%HT1D_WALL_TO_LINE_H))
                    IF (.NOT.HT1D_SAVED(NM)%VALID(IW)) CYCLE
                    LINE = GM%HT1D_WALL_TO_LINE_H(IW)
                    IF (LINE<1 .OR. LINE>GM%HT1D_N_LINES) CYCLE
                    IF (GM%HT1D_BACK_REMOTE_H(LINE)==0 .OR. GM%HT1D_BACKING_H(LINE)/=EXPOSED) CYCLE
                    A_H(LINE) = HT1D_SAVED(NM)%VALUES(IW,IV)
                ENDDO
            END SUBROUTINE RESTORE_LINE_VALUES

        END SUBROUTINE HT1D_RESTORE_BACKSIDE_GPU


        LOGICAL FUNCTION HT1D_GPU_WALL_ACTIVE(NM,WALL_INDEX)
            INTEGER, INTENT(IN) :: NM,WALL_INDEX
            INTEGER :: LINE
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            HT1D_GPU_WALL_ACTIVE = .FALSE.
            GM => GPU_MESHES(NM)
            IF (.NOT.GM%HT1D_INITIALIZED .OR. .NOT.ALLOCATED(GM%HT1D_WALL_TO_LINE_H)) RETURN
            IF (WALL_INDEX<1 .OR. WALL_INDEX>SIZE(GM%HT1D_WALL_TO_LINE_H)) RETURN
            LINE = GM%HT1D_WALL_TO_LINE_H(WALL_INDEX)
            IF (LINE<1 .OR. LINE>GM%HT1D_N_LINES) RETURN
            IF (GM%HT1D_BACK_REMOTE_H(LINE)/=0) THEN
                IF (.NOT.ALLOCATED(GM%HT1D_BACKSIDE_VALID_H)) RETURN
                IF (GM%HT1D_BACKSIDE_VALID_H(LINE)==0) RETURN
            ENDIF
            ! An exposed backside may be either another GPU HT1D line or a
            ! regular thin WALL (for example FIRE in cabinet_06). The latter
            ! uses the ordinary device wall arrays directly.
            IF (GM%HT1D_BACKING_H(LINE)==EXPOSED .AND. GM%HT1D_BACK_INDEX_H(LINE)<=0) RETURN
            HT1D_GPU_WALL_ACTIVE = .TRUE.
        END FUNCTION HT1D_GPU_WALL_ACTIVE

        !> \brief Heat flux of the liquid droplets on the WALL cells of the device lines, as in wall.f90
        !> \details SOLID_HEAT_TRANSFER takes Q_LIQUID_F = -SUM(B2%LP_CPUA) + B1%Q_CONDENSE at the front and, for an
        !> EXPOSED back side, Q_LIQUID_B = -SUM(B2_BACK%LP_CPUA) + B1%Q_CONDENSE. LP_CPUA is the running average that
        !> PARTICLE_MASS_ENERGY_TRANSFER keeps on the host; it is called after the particles of all meshes, before WALL_BC.
        SUBROUTINE HT1D_SET_LIQUID_GPU(NM)
            USE GLOBAL_CONSTANTS, ONLY: N_LP_ARRAY_INDICES
            INTEGER, INTENT(IN) :: NM
            INTEGER :: IW,IL,BM,BI
            REAL(EB), ALLOCATABLE :: QF(:),QB(:)
            TYPE(MESH_TYPE), POINTER :: M,MB
            TYPE(GPU_MESH_TYPE), POINTER :: GM
            TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1
            TYPE(BOUNDARY_PROP2_TYPE), POINTER :: B2,B2_BACK

            IF (.NOT.LIQUID_DROPLETS) RETURN
            GM => GPU_MESHES(NM)
            IF (.NOT.GM%HT1D_INITIALIZED .OR. GM%HT1D_N_LINES<=0) RETURN
            IF (.NOT.ALLOCATED(GM%HT1D_WALL_TO_LINE_H) .OR. .NOT.ALLOCATED(GM%HT1D_Q_LIQUID_F_D)) RETURN
            M => MESHES(NM)
            ALLOCATE(QF(GM%HT1D_N_LINES),QB(GM%HT1D_N_LINES))
            QF = 0._EB
            QB = 0._EB
            DO IW=1,SIZE(GM%HT1D_WALL_TO_LINE_H)
                IL = GM%HT1D_WALL_TO_LINE_H(IW)
                IF (IL<1 .OR. IL>GM%HT1D_N_LINES) CYCLE
                B1 => M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)
                B2 => M%BOUNDARY_PROP2(M%WALL(IW)%B2_INDEX)
                QF(IL) = -SUM(B2%LP_CPUA(:)) + B1%Q_CONDENSE
                IF (GM%HT1D_BACKING_H(IL)==EXPOSED .AND. N_LP_ARRAY_INDICES>0) THEN
                    BM = GM%HT1D_BACK_MESH_H(IL)
                    BI = GM%HT1D_BACK_INDEX_H(IL)
                    MB => MESHES(BM)
                    B2_BACK => MB%BOUNDARY_PROP2(MB%WALL(BI)%B2_INDEX)
                    QB(IL) = -SUM(B2_BACK%LP_CPUA(:)) + B1%Q_CONDENSE
                ENDIF
            ENDDO
            CALL GPU_WAIT(GM%STRM)
            GM%HT1D_Q_LIQUID_F_D = QF
            GM%HT1D_Q_LIQUID_B_D = QB
            DEALLOCATE(QF,QB)
        END SUBROUTINE HT1D_SET_LIQUID_GPU

        SUBROUTINE SOLID_HEAT_TRANSFER_GPU(NM,T,DT_BC,TMPMIN_IN,TMPMAX_IN,RADIATION_FLAG)
            INTEGER, INTENT(IN) :: NM,RADIATION_FLAG
            REAL(EB), INTENT(IN) :: T,DT_BC,TMPMIN_IN,TMPMAX_IN

            INTEGER :: GRDD,ISUB,MAX_SUBSTEPS,ISTAT
            INTEGER, PINNED, ALLOCATABLE, SAVE :: N_ACTIVE(:)
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            IF (.NOT.ALLOCATED(N_ACTIVE)) ALLOCATE(N_ACTIVE(1))

            IF (DT_BC<=TWENTY_EPSILON_EB) RETURN
            GM => GPU_MESHES(NM)
            IF (.NOT.GM%HT1D_INITIALIZED .OR. GM%HT1D_N_LINES<=0) RETURN
            IF (.NOT.ALLOCATED(GM%HT1D_WALL_INDEX_D)) RETURN

            ! Advance the device-resident line state using the cached index maps.
            GRDD = (GM%HT1D_N_LINES+HT1D_THREADS-1)/HT1D_THREADS
            CALL HT1D_COMPUTE_HTC_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%WALL_UB,GM%HT1D_WALL_INDEX_D, &
                GM%WALL_TOPO_AOS,GM%WALL_SF_INDEX,SF_THERMAL_BC_INDEX,SF_H_FIXED,SF_CONV_LENGTH,GM%WALL_RDN,GM%WALL_U_TANG, &
                GM%WALL_TMP_G,GM%WALL_TMP_F,GM%WALL_RHO_G,GM%WALL_ZZ_G_WORKD,MU_RSQMW_ZD,K_RSQMW_ZD,RSQ_MW_ZD, &
                GM%WALL_HEAT_TRANS_COEF,GRAV,PR_AIR,N_TRACKED_SPECIES,I_MAX_TEMP, &
                SF_RAMP_H_FIXED_INDEX,GM%WALL_K_G,MERGE(1,0,SIM_MODE==DNS_MODE .OR. SOLID_PHASE_ONLY),T-T_BEGIN, &
                RAMP_T_MIN_D,RAMP_SPAN_D,RAMP_RDT_D,RAMP_NPOINTS_D,RAMP_OFFSET_D,RAMP_INTERP_D)
            CALL HT1D_LOAD_BOUNDARY_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%HT1D_WALL_INDEX_D, &
                GM%HT1D_BACK_INDEX_D,GM%HT1D_BACK_LINE_D,GM%HT1D_BACK_MESH_D,GM%HT1D_BACK_REMOTE_D, &
                GM%HT1D_BACKSIDE_VALID_D,GM%HT1D_BACKING_D,GM%WALL_TOPO_AOS,GM%WALL_TMP_G,GM%WALL_TMP_F, &
                GM%WALL_HEAT_TRANS_COEF,GM%WALL_Q_RAD_IN,GM%WALL_EMISSIVITY,GM%TMP_0D, &
                GM%HT1D_TMP_G_F_D,GM%HT1D_TMP_G_B_D,GM%HT1D_TMP_F_D,GM%HT1D_TMP_B_D,GM%HT1D_HTCF_D, &
                GM%HT1D_HTCB_D,GM%HT1D_Q_RAD_IN_F_D,GM%HT1D_Q_RAD_IN_B_D,GM%HT1D_EMISSIVITY_F_D, &
                GM%HT1D_EMISSIVITY_B_D,GM%HT1D_RAD_FRONT_D,GM%HT1D_RAD_BACK_D,GM%HT1D_DIRICHLET_FRONT_D, &
                GM%HT1D_DIRICHLET_BACK_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_DT_SUB_D,GM%HT1D_DXF_D,GM%HT1D_DXB_D, &
                RADIATION_FLAG,T-T_BEGIN,GM%HT1D_H_FIXED_B_D,GM%HT1D_TMP_G_BACK_D,GM%HT1D_RAMP_H_FIXED_B_D, &
                GM%HT1D_RAMP_TMP_G_BACK_D,GM%HT1D_DIR_BACK_FIX_D,GM%HT1D_TMP_BACK_D,GM%HT1D_RAMP_TB_D, &
                RAMP_T_MIN_D,RAMP_SPAN_D,RAMP_RDT_D,RAMP_NPOINTS_D,RAMP_OFFSET_D,RAMP_INTERP_D,GM%HT1D_INT_RAD_D)

            CALL HT1D_PREPARE_SOURCE_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                GM%HT1D_WALL_INDEX_D,GM%HT1D_SURF_INDEX_D,GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_DX_D, &
                GM%HT1D_Q_BASE_D,GM%HT1D_Q_S_D,GM%WALL_M_DOT_G_PP_ADJUST,SF_PYROLYSIS_MODEL,SF_H_V, &
                REAC_FUEL_SMIX_INDEXD,N_REACTIONS,N_TRACKED_SPECIES,GM%WALL_LB,GM%WALL_UB)

            CALL HT1D_INIT_SUBSTEP_BATCH_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%HT1D_COEFF_VALID_D, &
                GM%HT1D_T_BC_SUB_D,GM%HT1D_Q_CON_ACCUM_D,GM%HT1D_Q_RAD_ACCUM_D,GM%HT1D_LINE_ACTIVE_D, &
                GM%HT1D_WALL_INDEX_D,GM%HT1D_INT_RAD_D,GM%WALL_Q_RAD_OUT,GM%HT1D_Q_RAD_OUT_OLD_D)

            ! Sub-time steps as in SOLID_HEAT_TRANSFER: internal radiation and the step size from the current
            ! temperatures and the thermal properties of the previous sub-step, then the properties and the solve.
            ! LINE_ACTIVE_D disables completed lines; the loop ends when no line is active.
            MAX_SUBSTEPS = MAX(1,GM%HT1D_MAX_SUBSTEPS)
            DO ISUB=1,MAX_SUBSTEPS
                CALL HT1D_INTERNAL_RADIATION_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                    GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_INT_RAD_D,GM%HT1D_TWO_DX_KAPPA_D, &
                    GM%HT1D_TMP_D,GM%HT1D_RDX_D,GM%HT1D_Q_RAD_IN_F_D,GM%HT1D_EMISSIVITY_F_D,GM%HT1D_Q_RAD_IN_B_D, &
                    GM%HT1D_EMISSIVITY_B_D,GM%HT1D_Q_RAD_OUT_OLD_D,GM%HT1D_Q_RAD_OUT_SUB_D,GM%HT1D_Q_IR_D)
                IF (CHECK_FO) THEN
                    CALL HT1D_BUILD_FO_LIMIT_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                        GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_DX_D,GM%HT1D_K_S_D,GM%HT1D_RHO_C_S_D, &
                        GM%HT1D_DT_FO_D,1)
                ENDIF
                CALL HT1D_SELECT_SUBSTEP_BATCH_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                    GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_Q_S_D,GM%HT1D_RHO_C_S_D, &
                    GM%HT1D_DT_FO_D,GM%HT1D_T_BC_SUB_D,GM%HT1D_DT_SUB_D,GM%HT1D_LINE_ACTIVE_D,DT_BC, &
                    GM%HT1D_DELTA_TMP_MAX_D,GM%HT1D_TIME_STEP_FACTOR_D,WALL_INCREMENT,TWENTY_EPSILON_EB, &
                    MERGE(1,0,CHECK_FO),MERGE(1,0,ICYC>WALL_INCREMENT), &
                    GM%HT1D_Q_IR_D,GM%HT1D_TMP_D,GM%HT1D_K_S_D,GM%HT1D_RDX_D,GM%HT1D_RDXN_D,GM%HT1D_INT_RAD_D, &
                    GM%HT1D_BACKING_D,GM%HT1D_H_FIXED_B_D,GM%HT1D_TMP_F_D,GM%HT1D_TMP_G_F_D,GM%HT1D_HTCF_D, &
                    GM%HT1D_Q_RAD_IN_F_D,GM%HT1D_EMISSIVITY_F_D,GM%HT1D_TMP_B_D,GM%HT1D_TMP_G_B_D,GM%HT1D_HTCB_D, &
                    GM%HT1D_Q_RAD_IN_B_D,GM%HT1D_EMISSIVITY_B_D)
                IF (.NOT.GM%HT1D_STATIC_PROPERTIES_INITIALIZED) THEN
                    CALL HT1D_BUILD_MATERIAL_PROPERTIES_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                        GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_MATL_OFFSET_D,GM%HT1D_N_MATL_D,GM%HT1D_LAYER_INDEX_D, &
                        GM%HT1D_MATL_INDEX_D,GM%HT1D_MATL_COMP_OFFSET_D,GM%HT1D_MATL_COMP_RHO_D,GM%HT1D_MATL_LAYER_OFFSET_D, &
                        GM%HT1D_DENSITY_ADJUST_D,GM%HT1D_PACKING_RATIO_D,GM%HT1D_MATL_RHO_S_D,GM%HT1D_MATL_K_S_D, &
                        GM%HT1D_MATL_C_S_D,GM%HT1D_TMP_D,GM%HT1D_DX_WGT_D,GM%HT1D_K_NODE_D,GM%HT1D_K_S_D, &
                        GM%HT1D_RHO_C_S_D,GM%HT1D_COEFF_VALID_D,I_MAX_TEMP)
                ENDIF
                CALL HT1D_BUILD_INTERIOR_COEFFICIENTS_BATCH_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>( &
                    GM%HT1D_N_LINES,GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_K_S_D, &
                    GM%HT1D_RHO_C_S_D,GM%HT1D_Q_S_D,GM%HT1D_TMP_D,GM%HT1D_RDX_D,GM%HT1D_RDXN_D,GM%HT1D_DT_SUB_D, &
                    GM%HT1D_AAS_D,GM%HT1D_BBS_D,GM%HT1D_DDS_D,GM%HT1D_CCS_D,GM%HT1D_DDT_D,GM%HT1D_Q_IR_D)
                CALL HT1D_CLOSE_BOUNDARIES_BATCH_GPU<<<GM%HT1D_N_LINES,1,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                    GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_K_S_D,GM%HT1D_TMP_D, &
                    GM%HT1D_DXF_D,GM%HT1D_DXB_D,GM%HT1D_HTCF_D,GM%HT1D_HTCB_D,GM%HT1D_TMP_G_F_D,GM%HT1D_TMP_G_B_D, &
                    GM%HT1D_TMP_F_D,GM%HT1D_TMP_B_D,GM%HT1D_Q_LIQUID_F_D,GM%HT1D_Q_LIQUID_B_D,GM%HT1D_Q_RAD_IN_F_D, &
                    GM%HT1D_Q_RAD_IN_B_D,GM%HT1D_EMISSIVITY_F_D,GM%HT1D_EMISSIVITY_B_D,GM%HT1D_RAD_FRONT_D, &
                    GM%HT1D_RAD_BACK_D,GM%HT1D_DIRICHLET_FRONT_D,GM%HT1D_DIRICHLET_BACK_D,GM%HT1D_AAS_D, &
                    GM%HT1D_BBS_D,GM%HT1D_CCS_D,GM%HT1D_DDT_D,GM%HT1D_RFACF2_D,GM%HT1D_QDXKF_D,GM%HT1D_RFACB2_D, &
                    GM%HT1D_QDXKB_D,GM%HT1D_BACKING_D,GM%HT1D_H_FIXED_B_D)
                CALL HT1D_THOMAS_SOLVE_BATCH_GPU<<<GM%HT1D_N_LINES,1,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                    GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_COEFF_VALID_D,GM%HT1D_AAS_D,GM%HT1D_BBS_D, &
                    GM%HT1D_CCS_D,GM%HT1D_DDT_D,TMPMIN_IN,TMPMAX_IN)
                CALL HT1D_COMMIT_TEMPERATURE_BATCH_GPU<<<GM%HT1D_N_LINES,HT1D_THREADS,0,GM%STRM>>>( &
                    GM%HT1D_N_LINES,GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_CCS_D,GM%HT1D_TMP_D, &
                    GM%HT1D_RFACF2_D,GM%HT1D_QDXKF_D,GM%HT1D_RFACB2_D,GM%HT1D_QDXKB_D,GM%HT1D_COEFF_VALID_D, &
                    TMPMIN_IN,TMPMAX_IN)
                CALL HT1D_UPDATE_SURFACE_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_INT_RAD_D,GM%HT1D_Q_RAD_OUT_SUB_D, &
                    GM%HT1D_Q_RAD_OUT_OLD_D,GM%HT1D_N_LINES,GM%HT1D_WALL_INDEX_D, &
                    GM%HT1D_NODE_OFFSET_D,GM%HT1D_NWP_D,GM%HT1D_TMP_D,GM%HT1D_TMP_G_F_D,GM%HT1D_TMP_F_D, &
                    GM%HT1D_TMP_B_D,GM%HT1D_HTCF_D,GM%HT1D_EMISSIVITY_F_D,GM%HT1D_COEFF_VALID_D, &
                    GM%HT1D_DT_SUB_D,GM%HT1D_Q_CON_ACCUM_D,GM%HT1D_Q_RAD_ACCUM_D,GM%WALL_TMP_F,GM%WALL_Q_CON_F, &
                    GM%WALL_Q_RAD_OUT,RADIATION_FLAG)
                CALL HT1D_ADVANCE_SUBSTEP_BATCH_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES, &
                    GM%HT1D_COEFF_VALID_D,GM%HT1D_LINE_ACTIVE_D,GM%HT1D_T_BC_SUB_D,GM%HT1D_DT_SUB_D,DT_BC,TWENTY_EPSILON_EB)
                IF (ISUB<MAX_SUBSTEPS) THEN
                    ISTAT = CUDAMEMSETASYNC(GM%HT1D_ACTIVE_COUNT_D,0,1,GM%STRM)
                    CALL HT1D_COUNT_ACTIVE_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%HT1D_LINE_ACTIVE_D, &
                        GM%HT1D_ACTIVE_COUNT_D)
                    ISTAT = CUDAMEMCPYASYNC(N_ACTIVE,GM%HT1D_ACTIVE_COUNT_D,1,CUDAMEMCPYDEVICETOHOST,GM%STRM)
                    CALL GPU_WAIT(GM%STRM)
                    IF (N_ACTIVE(1)==0) EXIT
                ENDIF
            ENDDO
            CALL HT1D_FINALIZE_SURFACE_BATCH_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%HT1D_WALL_INDEX_D, &
                GM%HT1D_Q_CON_ACCUM_D,GM%HT1D_Q_RAD_ACCUM_D,GM%HT1D_EMISSIVITY_F_D,GM%WALL_Q_CON_F, &
                GM%WALL_Q_RAD_OUT,DT_BC,RADIATION_FLAG,GM%HT1D_INT_RAD_D)
            CALL HT1D_UPDATE_IGNITION_GPU<<<GRDD,HT1D_THREADS,0,GM%STRM>>>(GM%HT1D_N_LINES,GM%HT1D_WALL_INDEX_D, &
                GM%HT1D_SURF_INDEX_D,GM%WALL_TMP_F,GM%WALL_M_DOT_G_PP_ADJUST,GM%WALL_T_IGN,SF_PYROLYSIS_MODEL, &
                SF_TMP_IGN,SF_TMP_EXT,N_TRACKED_SPECIES,GM%WALL_LB,GM%WALL_UB,T)

            ! Following wall kernels consume WALL_TMP_F, WALL_Q_CON_F and WALL_Q_RAD_OUT.
        END SUBROUTINE SOLID_HEAT_TRANSFER_GPU


        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_PREPARE_SOURCE_GPU(N_LINES,WALL_INDEX_D,SURF_INDEX_D,NODE_OFFSET_D,NWP_D, &
            DX_D,Q_BASE_D,Q_S_D,WALL_M_DOT_ADJUST_D,SF_PYROLYSIS_MODEL_D,SF_H_V_D,REAC_FUEL_INDEX_D,N_REACTIONS_IN, &
            N_TRACKED_SPECIES_IN,WALL_LB,WALL_UB)
            INTEGER, VALUE :: N_LINES,N_REACTIONS_IN,N_TRACKED_SPECIES_IN,WALL_LB,WALL_UB
            INTEGER, DEVICE :: WALL_INDEX_D(*),SURF_INDEX_D(*),NODE_OFFSET_D(*),NWP_D(*)
            INTEGER, DEVICE :: SF_PYROLYSIS_MODEL_D(0:*),REAC_FUEL_INDEX_D(*)
            REAL(EB), DEVICE :: DX_D(*),Q_BASE_D(*),Q_S_D(*),SF_H_V_D(0:*)
            REAL(EB), DEVICE :: WALL_M_DOT_ADJUST_D(WALL_LB:WALL_UB,1:*)

            INTEGER :: LINE,I,IW,SF_IDX,BASE,NWP,FUEL_INDEX

            LINE = BLOCKIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            DO I=THREADIDX%X,NWP,BLOCKDIM%X
                Q_S_D(BASE+I) = Q_BASE_D(BASE+I)
            ENDDO
            IF (THREADIDX%X/=1 .OR. NWP<1 .OR. N_REACTIONS_IN<1) RETURN

            IW = WALL_INDEX_D(LINE)
            SF_IDX = SURF_INDEX_D(LINE)
            IF (SF_PYROLYSIS_MODEL_D(SF_IDX)/=PYROLYSIS_SPECIFIED) RETURN
            FUEL_INDEX = REAC_FUEL_INDEX_D(1)
            IF (FUEL_INDEX<1 .OR. FUEL_INDEX>N_TRACKED_SPECIES_IN) RETURN
            IF (DX_D(BASE+1)>TWENTY_EPSILON_EB) Q_S_D(BASE+1) = Q_S_D(BASE+1) - &
                WALL_M_DOT_ADJUST_D(IW,FUEL_INDEX)*SF_H_V_D(SF_IDX)/DX_D(BASE+1)
        END SUBROUTINE HT1D_PREPARE_SOURCE_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_UPDATE_IGNITION_GPU(N_LINES,WALL_INDEX_D,SURF_INDEX_D,WALL_TMP_F_D, &
            WALL_M_DOT_G_PP_ADJUST_D,WALL_T_IGN_D,SF_PYROLYSIS_MODEL_D,SF_TMP_IGN_D,SF_TMP_EXT_D, &
            N_TRACKED_SPECIES_IN,WALL_LB,WALL_UB,T_IN)
            INTEGER, VALUE :: N_LINES,N_TRACKED_SPECIES_IN,WALL_LB,WALL_UB
            REAL(EB), VALUE :: T_IN
            INTEGER, DEVICE :: WALL_INDEX_D(*),SURF_INDEX_D(*),SF_PYROLYSIS_MODEL_D(0:*)
            REAL(EB), DEVICE :: WALL_TMP_F_D(0:*),WALL_T_IGN_D(0:*),SF_TMP_IGN_D(0:*),SF_TMP_EXT_D(0:*)
            REAL(EB), DEVICE :: WALL_M_DOT_G_PP_ADJUST_D(WALL_LB:WALL_UB,1:*)

            INTEGER :: LINE,IW,SF_IDX,N
            REAL(EB) :: M_DOT_SUM

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            IW = WALL_INDEX_D(LINE)
            SF_IDX = SURF_INDEX_D(LINE)
            IF (SF_PYROLYSIS_MODEL_D(SF_IDX)/=PYROLYSIS_SPECIFIED) RETURN

            IF (WALL_T_IGN_D(IW)>T_IN) THEN
                M_DOT_SUM = 0._EB
                DO N=1,N_TRACKED_SPECIES_IN
                    M_DOT_SUM = M_DOT_SUM + WALL_M_DOT_G_PP_ADJUST_D(IW,N)
                ENDDO
                IF (M_DOT_SUM>0._EB .OR. WALL_TMP_F_D(IW)>=SF_TMP_IGN_D(SF_IDX)) WALL_T_IGN_D(IW) = T_IN
            ENDIF
            IF (SF_TMP_IGN_D(SF_IDX)<50000._EB .AND. WALL_TMP_F_D(IW)<SF_TMP_EXT_D(SF_IDX) .AND. &
                WALL_T_IGN_D(IW)<T_IN) WALL_T_IGN_D(IW) = HUGE(1._EB)
        END SUBROUTINE HT1D_UPDATE_IGNITION_GPU

        SUBROUTINE HT1D_SYNC_OUTPUT_D2H(NM)
            INTEGER, INTENT(IN) :: NM
            INTEGER :: IW,LINE,BASE,NWP
            TYPE(MESH_TYPE), POINTER :: M
            TYPE(WALL_TYPE), POINTER :: WC
            TYPE(BOUNDARY_ONE_D_TYPE), POINTER :: ONE_D
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            GM => GPU_MESHES(NM)
            IF (.NOT.GM%HT1D_INITIALIZED .OR. GM%HT1D_N_LINES<=0) RETURN
            IF (.NOT.ALLOCATED(GM%HT1D_TMP_D) .OR. .NOT.ALLOCATED(GM%HT1D_TMP_H)) RETURN

            ! Copy the compact solid state for CPU DEVC output through ONE_D%TMP.
            CALL GPU_WAIT(GM%STRM)
            GM%HT1D_TMP_H = GM%HT1D_TMP_D

            M => MESHES(NM)
            IF (.NOT.ALLOCATED(GM%HT1D_WALL_TO_LINE_H) .OR. .NOT.ALLOCATED(M%BOUNDARY_ONE_D)) RETURN
            DO IW=1,SIZE(GM%HT1D_WALL_TO_LINE_H)
                LINE = GM%HT1D_WALL_TO_LINE_H(IW)
                IF (LINE<1 .OR. LINE>GM%HT1D_N_LINES) CYCLE
                WC => M%WALL(IW)
                IF (WC%OD_INDEX<1 .OR. WC%OD_INDEX>SIZE(M%BOUNDARY_ONE_D)) CYCLE
                ONE_D => M%BOUNDARY_ONE_D(WC%OD_INDEX)
                NWP = GM%HT1D_NWP_H(LINE)
                BASE = GM%HT1D_NODE_OFFSET_H(LINE)
                IF (.NOT.ALLOCATED(ONE_D%TMP)) CYCLE
                IF (UBOUND(ONE_D%TMP,1)<NWP+1) CYCLE
                ONE_D%TMP(0:NWP+1) = GM%HT1D_TMP_H(BASE:BASE+NWP+1)
                M%BOUNDARY_PROP1(WC%B1_INDEX)%TMP_B = 0.5_EB*(ONE_D%TMP(NWP)+ONE_D%TMP(NWP+1))
            ENDDO
        END SUBROUTINE HT1D_SYNC_OUTPUT_D2H

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_COMPUTE_HTC_GPU(N_LINES,TOTAL_WALL_CELLS,WALL_INDEX_D,WALL_TOPO,WALL_SF_INDEX_D, &
            SF_THERMAL_BC_INDEX_D,SF_H_FIXED_D,SF_CONV_LENGTH_D,WALL_RDN_D,WALL_U_TANG_D,WALL_TMP_G_D,WALL_TMP_F_D, &
            WALL_RHO_G_D,WALL_ZZ_GD,MU_RSQMW_ZD_IN,K_RSQMW_ZD_IN,RSQ_MW_ZD_IN,WALL_HEAT_TRANS_COEF_D, &
            GRAV_IN,PR_AIR_IN,N_TRACKED_SPECIES,I_MAX_TEMP_IN, &
            SF_RAMP_H_FIXED_INDEX_D,WALL_K_G_D,RESOLVED_HTC,T_ELAPSED, &
            RAMP_T_MIN_D,RAMP_SPAN_D,RAMP_RDT_D,RAMP_NPOINTS_D,RAMP_OFFSET_D,RAMP_INTERP_D)
            ! HEAT_TRANSFER_COEFFICIENT (func.f90) for a WALL cell with the default model: CONSTANT_HTC for a
            ! specified HEAT_TRANSFER_COEFFICIENT (with RAMP_HEAT_TRANSFER_COEFFICIENT), 2*K_G*RDN for DNS or
            ! SOLID_PHASE_ONLY, otherwise the natural/forced convection correlations.
            INTEGER, VALUE :: N_LINES,TOTAL_WALL_CELLS,N_TRACKED_SPECIES,I_MAX_TEMP_IN,RESOLVED_HTC
            REAL(EB), VALUE :: T_ELAPSED
            INTEGER, DEVICE :: SF_RAMP_H_FIXED_INDEX_D(0:*)
            REAL(EB), DEVICE :: WALL_K_G_D(0:*)
            REAL(EB), DEVICE :: RAMP_T_MIN_D(0:*),RAMP_SPAN_D(0:*),RAMP_RDT_D(0:*),RAMP_INTERP_D(*)
            INTEGER, DEVICE :: RAMP_NPOINTS_D(0:*),RAMP_OFFSET_D(0:*)
            INTEGER, DEVICE :: WALL_INDEX_D(*),WALL_SF_INDEX_D(0:*),SF_THERMAL_BC_INDEX_D(0:*)
            TYPE(WALL_TOPO_AOS_TYPE), DEVICE :: WALL_TOPO(0:*)
            REAL(EB), DEVICE :: SF_H_FIXED_D(0:*),SF_CONV_LENGTH_D(0:*),WALL_RDN_D(0:*),WALL_U_TANG_D(0:*)
            REAL(EB), DEVICE :: WALL_TMP_G_D(0:*),WALL_TMP_F_D(0:*),WALL_RHO_G_D(0:*)
            REAL(EB), DEVICE :: WALL_ZZ_GD(1:TOTAL_WALL_CELLS,1:*),MU_RSQMW_ZD_IN(0:I_MAX_TEMP_IN,1:*), &
                                K_RSQMW_ZD_IN(0:I_MAX_TEMP_IN,1:*),RSQ_MW_ZD_IN(*)
            REAL(EB), DEVICE :: WALL_HEAT_TRANS_COEF_D(0:*)
            REAL(EB), VALUE :: GRAV_IN,PR_AIR_IN

            INTEGER :: LINE,IW,SF_IDX,ITMP,N,IOR
            REAL(EB) :: H_FIXED,CONV_LENGTH,DN,TMP_G,TMP_F,DTMP,TMP_FILM,RE,GR,RA,NUSSELT_FORCED,NUSSELT_FREE
            REAL(EB) :: MU_G,K_G,NUMER,DENOM,PR_ONTH,ONTH,ONSI

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            IW = WALL_INDEX_D(LINE)
            IF (WALL_TOPO(IW)%BOUNDARY_TYPE==0) RETURN
            SF_IDX = WALL_SF_INDEX_D(IW)
            IF (SF_THERMAL_BC_INDEX_D(SF_IDX)/=THERMALLY_THICK) RETURN

            H_FIXED = SF_H_FIXED_D(SF_IDX)
            IF (H_FIXED>=0._EB) THEN
                IF (SF_RAMP_H_FIXED_INDEX_D(SF_IDX)>0) H_FIXED = H_FIXED*EVALUATE_RAMP_DEVICE(T_ELAPSED, &
                    SF_RAMP_H_FIXED_INDEX_D(SF_IDX),1._EB,RAMP_T_MIN_D,RAMP_SPAN_D,RAMP_RDT_D,RAMP_NPOINTS_D, &
                    RAMP_OFFSET_D,RAMP_INTERP_D)
                WALL_HEAT_TRANS_COEF_D(IW) = H_FIXED
                RETURN
            ENDIF
            IF (RESOLVED_HTC/=0) THEN
                WALL_HEAT_TRANS_COEF_D(IW) = 2._EB*WALL_K_G_D(IW)*WALL_RDN_D(IW)
                RETURN
            ENDIF

            CONV_LENGTH = SF_CONV_LENGTH_D(SF_IDX)
            TMP_G = WALL_TMP_G_D(IW)
            TMP_F = WALL_TMP_F_D(IW)
            DTMP = TMP_G-TMP_F
            TMP_FILM = MAX(1._EB,TMP_F+(1._EB/3._EB)*DTMP)
            ITMP = MAX(0,MIN(I_MAX_TEMP_IN,NINT(TMP_FILM)))
            NUMER = 0._EB
            DENOM = 0._EB
            DO N=1,N_TRACKED_SPECIES
                NUMER = NUMER+K_RSQMW_ZD_IN(ITMP,N)*WALL_ZZ_GD(IW,N)
                DENOM = DENOM+WALL_ZZ_GD(IW,N)*RSQ_MW_ZD_IN(N)
            ENDDO
            IF (ABS(DENOM)>TWENTY_EPSILON_EB) THEN
                K_G = NUMER/DENOM
            ELSE
                K_G = 0._EB
            ENDIF
            NUMER = 0._EB
            DENOM = 0._EB
            DO N=1,N_TRACKED_SPECIES
                NUMER = NUMER+MU_RSQMW_ZD_IN(ITMP,N)*WALL_ZZ_GD(IW,N)
                DENOM = DENOM+WALL_ZZ_GD(IW,N)*RSQ_MW_ZD_IN(N)
            ENDDO
            IF (ABS(DENOM)>TWENTY_EPSILON_EB) THEN
                MU_G = NUMER/DENOM
            ELSE
                MU_G = 0._EB
            ENDIF
            IF (ABS(MU_G)<=TWENTY_EPSILON_EB .OR. ABS(K_G)<=TWENTY_EPSILON_EB .OR. CONV_LENGTH<=TWENTY_EPSILON_EB) THEN
                WALL_HEAT_TRANS_COEF_D(IW) = 0._EB
                RETURN
            ENDIF

            ONTH = 1._EB/3._EB
            ONSI = 1._EB/6._EB
            PR_ONTH = PR_AIR_IN**ONTH
            RE = MAX(0._EB,WALL_RHO_G_D(IW)*WALL_U_TANG_D(IW)*CONV_LENGTH/MU_G)
            GR = GRAV_IN*ABS(DTMP)*CONV_LENGTH**3*(WALL_RHO_G_D(IW)/MU_G)**2/TMP_FILM
            NUSSELT_FORCED = 0.0296_EB*RE**0.8_EB*PR_ONTH
            RA = GR*PR_AIR_IN
            IOR = WALL_TOPO(IW)%IOR
            SELECT CASE(ABS(IOR))
                CASE(0:2)
                    NUSSELT_FREE = (0.825_EB+0.324_EB*RA**ONSI)**2
                CASE(3)
                    IF ((IOR==3 .AND. DTMP<0._EB) .OR. (IOR==-3 .AND. DTMP>=0._EB)) THEN
                        IF (RA<1.E7_EB) THEN
                            NUSSELT_FREE = 0.54_EB*RA**0.25_EB
                        ELSE
                            NUSSELT_FREE = 0.15_EB*RA**ONTH
                        ENDIF
                    ELSE
                        NUSSELT_FREE = 0.52_EB*RA**0.2  ! 4-byte 0.2 as in FDS turb.f90
                    ENDIF
                CASE DEFAULT
                    NUSSELT_FREE = 0._EB
            END SELECT
            WALL_HEAT_TRANS_COEF_D(IW) = MAX(NUSSELT_FREE,NUSSELT_FORCED,2._EB*CONV_LENGTH*MAX(0._EB,WALL_RDN_D(IW)))* &
                K_G/CONV_LENGTH
        END SUBROUTINE HT1D_COMPUTE_HTC_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_LOAD_BOUNDARY_GPU(N_LINES,WALL_INDEX_D,BACK_INDEX_D,BACK_LINE_D,BACK_MESH_D, &
            BACK_REMOTE_D,BACKSIDE_VALID_D,BACKING_D,WALL_TOPO, &
            WALL_TMP_G_D,WALL_TMP_F_D,WALL_HEAT_TRANS_COEF_D,WALL_Q_RAD_IN_D,WALL_EMISSIVITY_D,TMP_0D, &
            TMP_G_F_D,TMP_G_B_D,TMP_F_D,TMP_B_D,HTCF_D,HTCB_D,Q_RAD_IN_F_D,Q_RAD_IN_B_D,EMISSIVITY_F_D, &
            EMISSIVITY_B_D,RAD_FRONT_D,RAD_BACK_D,DIRICHLET_FRONT_D,DIRICHLET_BACK_D,COEFF_VALID_D,DT_SUB_D, &
            DXF_D,DXB_D,RADIATION_FLAG,T_ELAPSED,H_FIXED_B_D,TMP_G_BACK_D,RAMP_H_FIXED_B_D,RAMP_TMP_G_BACK_D, &
            DIR_BACK_FIX_D,TMP_BACK_FIX_D,RAMP_TB_D,RAMP_T_MIN,RAMP_SPAN,RAMP_RDT,RAMP_NPOINTS,RAMP_OFFSET,RAMP_INTERP, &
            INT_RAD_D)
            INTEGER, VALUE :: N_LINES,RADIATION_FLAG
            INTEGER, DEVICE :: INT_RAD_D(*)
            INTEGER, DEVICE :: WALL_INDEX_D(*),BACK_INDEX_D(*),BACK_LINE_D(*),BACK_MESH_D(*),BACK_REMOTE_D(*), &
                                BACKSIDE_VALID_D(*),BACKING_D(*),COEFF_VALID_D(*)
            INTEGER, DEVICE :: RAD_FRONT_D(*),RAD_BACK_D(*),DIRICHLET_FRONT_D(*),DIRICHLET_BACK_D(*)
            TYPE(WALL_TOPO_AOS_TYPE), DEVICE :: WALL_TOPO(0:*)
            REAL(EB), DEVICE :: WALL_TMP_G_D(0:*),WALL_TMP_F_D(0:*),WALL_HEAT_TRANS_COEF_D(0:*),WALL_Q_RAD_IN_D(0:*), &
                                WALL_EMISSIVITY_D(0:*)
            REAL(EB), DEVICE :: TMP_0D(0:*),TMP_G_F_D(*),TMP_G_B_D(*),TMP_F_D(*),TMP_B_D(*)
            REAL(EB), DEVICE :: HTCF_D(*),HTCB_D(*),Q_RAD_IN_F_D(*),Q_RAD_IN_B_D(*),EMISSIVITY_F_D(*),EMISSIVITY_B_D(*)
            REAL(EB), DEVICE :: DT_SUB_D(*),DXF_D(*),DXB_D(*)
            REAL(EB), VALUE :: T_ELAPSED
            REAL(EB), DEVICE :: H_FIXED_B_D(*),TMP_G_BACK_D(*)
            INTEGER, DEVICE :: RAMP_H_FIXED_B_D(*),RAMP_TMP_G_BACK_D(*)
            INTEGER, DEVICE :: DIR_BACK_FIX_D(*),RAMP_TB_D(*)
            REAL(EB), DEVICE :: TMP_BACK_FIX_D(*)
            REAL(EB), DEVICE :: RAMP_T_MIN(0:*),RAMP_SPAN(0:*),RAMP_RDT(0:*),RAMP_INTERP(*)
            INTEGER, DEVICE :: RAMP_NPOINTS(0:*),RAMP_OFFSET(0:*)

            INTEGER :: LINE,IW,BL,BACKING

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN

            IW = WALL_INDEX_D(LINE)
            COEFF_VALID_D(LINE) = 1
            TMP_G_F_D(LINE) = WALL_TMP_G_D(IW)
            TMP_F_D(LINE) = WALL_TMP_F_D(IW)
            HTCF_D(LINE) = MAX(0._EB,WALL_HEAT_TRANS_COEF_D(IW))
            Q_RAD_IN_F_D(LINE) = WALL_Q_RAD_IN_D(IW)
            EMISSIVITY_F_D(LINE) = MAX(0._EB,WALL_EMISSIVITY_D(IW))
            RAD_FRONT_D(LINE) = RADIATION_FLAG
            DIRICHLET_FRONT_D(LINE) = 0
            RAD_BACK_D(LINE) = 0
            DIRICHLET_BACK_D(LINE) = 0

            BACKING = BACKING_D(LINE)
            IF (BACKING==EXPOSED .AND. BACK_REMOTE_D(LINE)/=0) THEN
                IF (BACKSIDE_VALID_D(LINE)==0) THEN
                    COEFF_VALID_D(LINE) = 0
                    RETURN
                ENDIF
                RAD_BACK_D(LINE) = RADIATION_FLAG
            ELSEIF (BACKING==VOID) THEN
                TMP_G_B_D(LINE) = TMP_0D(WALL_TOPO(IW)%KK)
                IF (TMP_G_BACK_D(LINE)>0._EB) TMP_G_B_D(LINE) = TMP_G_B_D(LINE) + &
                    EVALUATE_RAMP_DEVICE(T_ELAPSED,RAMP_TMP_G_BACK_D(LINE),1._EB, &
                        RAMP_T_MIN,RAMP_SPAN,RAMP_RDT,RAMP_NPOINTS,RAMP_OFFSET,RAMP_INTERP)* &
                    (TMP_G_BACK_D(LINE)-TMP_G_B_D(LINE))
                IF (H_FIXED_B_D(LINE)>=0._EB) THEN
                    HTCB_D(LINE) = H_FIXED_B_D(LINE)
                    IF (RAMP_H_FIXED_B_D(LINE)>0) HTCB_D(LINE) = HTCB_D(LINE)* &
                        EVALUATE_RAMP_DEVICE(T_ELAPSED,RAMP_H_FIXED_B_D(LINE),1._EB, &
                            RAMP_T_MIN,RAMP_SPAN,RAMP_RDT,RAMP_NPOINTS,RAMP_OFFSET,RAMP_INTERP)
                ENDIF
                Q_RAD_IN_B_D(LINE) = EMISSIVITY_B_D(LINE)*SIGMA*TMP_G_B_D(LINE)**4
                RAD_BACK_D(LINE) = RADIATION_FLAG
                IF (DIR_BACK_FIX_D(LINE)/=0) THEN
                    ! B1%TMP_B = TMP_0(KK) + RAMP(TIME_TB)*(SF%TMP_BACK-TMP_0(KK))
                    DIRICHLET_BACK_D(LINE) = 1
                    TMP_B_D(LINE) = TMP_0D(WALL_TOPO(IW)%KK) + &
                        EVALUATE_RAMP_DEVICE(T_ELAPSED,RAMP_TB_D(LINE),1._EB, &
                            RAMP_T_MIN,RAMP_SPAN,RAMP_RDT,RAMP_NPOINTS,RAMP_OFFSET,RAMP_INTERP)* &
                        (TMP_BACK_FIX_D(LINE)-TMP_0D(WALL_TOPO(IW)%KK))
                ENDIF
            ELSEIF (BACKING==EXPOSED) THEN
                BL = BACK_LINE_D(LINE)
                IF (BL>0) THEN
                    IW = WALL_INDEX_D(BL)
                ELSE
                    IW = BACK_INDEX_D(LINE)
                ENDIF
                IF (IW>0) THEN
                    TMP_G_B_D(LINE) = WALL_TMP_G_D(IW)
                    ! TMP_B_D keeps this line's own back surface temperature (B1%TMP_B in wall.f90), not the back wall's TMP_F
                    HTCB_D(LINE) = MAX(0._EB,WALL_HEAT_TRANS_COEF_D(IW))
                    Q_RAD_IN_B_D(LINE) = WALL_Q_RAD_IN_D(IW)
                    EMISSIVITY_B_D(LINE) = MAX(0._EB,WALL_EMISSIVITY_D(IW))
                    RAD_BACK_D(LINE) = RADIATION_FLAG
                ENDIF
            ELSE
                Q_RAD_IN_B_D(LINE) = 0._EB
                EMISSIVITY_B_D(LINE) = 0._EB
                HTCB_D(LINE) = 0._EB
                TMP_G_B_D(LINE) = TMP_F_D(LINE)
                TMP_B_D(LINE) = TMP_F_D(LINE)
            ENDIF
            ! With internal radiation the surface radiation enters through Q_IR (wall.f90)
            IF (INT_RAD_D(LINE)/=0) THEN
                RAD_FRONT_D(LINE) = 0
                RAD_BACK_D(LINE) = 0
            ENDIF
        END SUBROUTINE HT1D_LOAD_BOUNDARY_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_UPDATE_SURFACE_GPU(INT_RAD_D,Q_RAD_OUT_SUB_D,Q_RAD_OUT_OLD_D, &
            N_LINES,WALL_INDEX_D,NODE_OFFSET_D,NWP_D,TMP_D,TMP_G_F_D, &
            TMP_F_OLD_D,TMP_B_D,HTCF_D,EMISSIVITY_D,COEFF_VALID_D,DT_SUB_D,Q_CON_ACCUM_D,Q_RAD_ACCUM_D,WALL_TMP_F_D, &
            WALL_Q_CON_F_D,WALL_Q_RAD_OUT_D,RADIATION_FLAG)
            INTEGER, VALUE :: N_LINES,RADIATION_FLAG
            INTEGER, DEVICE :: WALL_INDEX_D(*),NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*)
            REAL(EB), DEVICE :: TMP_D(*),TMP_G_F_D(*),TMP_F_OLD_D(*),TMP_B_D(*),HTCF_D(*),EMISSIVITY_D(*)
            REAL(EB), DEVICE :: DT_SUB_D(*),Q_CON_ACCUM_D(*),Q_RAD_ACCUM_D(*)
            REAL(EB), DEVICE :: WALL_TMP_F_D(0:*),WALL_Q_CON_F_D(0:*),WALL_Q_RAD_OUT_D(0:*)
            INTEGER, DEVICE :: INT_RAD_D(*)
            REAL(EB), DEVICE :: Q_RAD_OUT_SUB_D(*),Q_RAD_OUT_OLD_D(*)

            INTEGER :: LINE,IW,BASE,NWP
            REAL(EB) :: TMP_F_OLD,TMP_F_NEW,TMP_B_NEW,DTMP,EMISSIVITY,DT_SUB

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. COEFF_VALID_D(LINE)==0) RETURN
            IW = WALL_INDEX_D(LINE)
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            IF (NWP<1) RETURN

            TMP_F_OLD = TMP_F_OLD_D(LINE)
            TMP_F_NEW = 0.5_EB*(TMP_D(BASE)+TMP_D(BASE+1))
            TMP_B_NEW = 0.5_EB*(TMP_D(BASE+NWP)+TMP_D(BASE+NWP+1))
            DTMP = TMP_G_F_D(LINE)-0.5_EB*(TMP_F_OLD+TMP_F_NEW)
            DT_SUB = DT_SUB_D(LINE)
            WALL_TMP_F_D(IW) = TMP_F_NEW
            Q_CON_ACCUM_D(LINE) = Q_CON_ACCUM_D(LINE)+HTCF_D(LINE)*DTMP*DT_SUB
            TMP_F_OLD_D(LINE) = TMP_F_NEW
            TMP_B_D(LINE) = TMP_B_NEW
            EMISSIVITY = MAX(0._EB,EMISSIVITY_D(LINE))
            IF (INT_RAD_D(LINE)/=0) THEN
                ! Internal radiation: time average of the emitted flux of the two-flux solution
                Q_RAD_OUT_OLD_D(LINE) = Q_RAD_OUT_SUB_D(LINE)
                Q_RAD_ACCUM_D(LINE) = Q_RAD_ACCUM_D(LINE)+Q_RAD_OUT_SUB_D(LINE)*DT_SUB
            ELSEIF (RADIATION_FLAG/=0) THEN
                Q_RAD_ACCUM_D(LINE) = Q_RAD_ACCUM_D(LINE)+DT_SUB*(TMP_F_OLD**4 + &
                    2._EB*TMP_F_OLD**3*(TMP_F_NEW-TMP_F_OLD))
            ENDIF
        END SUBROUTINE HT1D_UPDATE_SURFACE_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_INIT_SUBSTEP_BATCH_GPU(N_LINES,COEFF_VALID_D,T_BC_SUB_D,Q_CON_ACCUM_D, &
            Q_RAD_ACCUM_D,LINE_ACTIVE_D,WALL_INDEX_D,INT_RAD_D,WALL_Q_RAD_OUT_D,Q_RAD_OUT_OLD_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: COEFF_VALID_D(*),LINE_ACTIVE_D(*),WALL_INDEX_D(*),INT_RAD_D(*)
            REAL(EB), DEVICE :: T_BC_SUB_D(*),Q_CON_ACCUM_D(*),Q_RAD_ACCUM_D(*),WALL_Q_RAD_OUT_D(0:*),Q_RAD_OUT_OLD_D(*)

            INTEGER :: LINE

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            T_BC_SUB_D(LINE) = 0._EB
            Q_CON_ACCUM_D(LINE) = 0._EB
            Q_RAD_ACCUM_D(LINE) = 0._EB
            LINE_ACTIVE_D(LINE) = COEFF_VALID_D(LINE)
            ! Q_RAD_OUT_OLD = B1%Q_RAD_OUT at the start of SOLID_HEAT_TRANSFER
            IF (INT_RAD_D(LINE)/=0) Q_RAD_OUT_OLD_D(LINE) = WALL_Q_RAD_OUT_D(WALL_INDEX_D(LINE))
        END SUBROUTINE HT1D_INIT_SUBSTEP_BATCH_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_ADVANCE_SUBSTEP_BATCH_GPU(N_LINES,COEFF_VALID_D,LINE_ACTIVE_D,T_BC_SUB_D, &
            DT_SUB_D,DT_BC,TWO_EPS_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: COEFF_VALID_D(*),LINE_ACTIVE_D(*)
            REAL(EB), DEVICE :: T_BC_SUB_D(*),DT_SUB_D(*)
            REAL(EB), VALUE :: DT_BC,TWO_EPS_D

            INTEGER :: LINE
            REAL(EB) :: T_BC_SUB,DT_SUB

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. LINE_ACTIVE_D(LINE)==0) RETURN
            DT_SUB = DT_SUB_D(LINE)
            T_BC_SUB = MIN(DT_BC,T_BC_SUB_D(LINE)+MAX(0._EB,DT_SUB))
            T_BC_SUB_D(LINE) = T_BC_SUB
            IF (DT_SUB<=TWO_EPS_D .OR. T_BC_SUB>=DT_BC-TWO_EPS_D) THEN
                LINE_ACTIVE_D(LINE) = 0
                COEFF_VALID_D(LINE) = 0
            ENDIF
        END SUBROUTINE HT1D_ADVANCE_SUBSTEP_BATCH_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_FINALIZE_SURFACE_BATCH_GPU(N_LINES,WALL_INDEX_D,Q_CON_ACCUM_D,Q_RAD_ACCUM_D, &
            EMISSIVITY_D,WALL_Q_CON_F_D,WALL_Q_RAD_OUT_D,DT_BC,RADIATION_FLAG,INT_RAD_D)
            INTEGER, VALUE :: N_LINES,RADIATION_FLAG
            INTEGER, DEVICE :: WALL_INDEX_D(*),INT_RAD_D(*)
            REAL(EB), DEVICE :: Q_CON_ACCUM_D(*),Q_RAD_ACCUM_D(*),EMISSIVITY_D(*)
            REAL(EB), DEVICE :: WALL_Q_CON_F_D(0:*),WALL_Q_RAD_OUT_D(0:*)
            REAL(EB), VALUE :: DT_BC

            INTEGER :: LINE,IW
            REAL(EB) :: EMISSIVITY

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. DT_BC<=TWENTY_EPSILON_EB) RETURN
            IW = WALL_INDEX_D(LINE)
            WALL_Q_CON_F_D(IW) = Q_CON_ACCUM_D(LINE)/DT_BC
            IF (INT_RAD_D(LINE)/=0) THEN
                WALL_Q_RAD_OUT_D(IW) = Q_RAD_ACCUM_D(LINE)/DT_BC
            ELSEIF (RADIATION_FLAG/=0) THEN
                EMISSIVITY = MAX(0._EB,EMISSIVITY_D(LINE))
                WALL_Q_RAD_OUT_D(IW) = SIGMA*EMISSIVITY*Q_RAD_ACCUM_D(LINE)/DT_BC
            ELSE
                WALL_Q_RAD_OUT_D(IW) = 0._EB
            ENDIF
        END SUBROUTINE HT1D_FINALIZE_SURFACE_BATCH_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_BUILD_FO_LIMIT_GPU(N_LINES,NODE_OFFSET_D,NWP_D,DX_D,K_S_D,RHO_C_S_D, &
            DT_FO_D,CHECK_FO_IN)
            INTEGER, VALUE :: N_LINES,CHECK_FO_IN
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*)
            REAL(EB), DEVICE :: DX_D(*),K_S_D(*),RHO_C_S_D(*),DT_FO_D(*)

            INTEGER :: LINE,BASE,NWP,TID,I,IDX,OFFSET
            REAL(EB) :: DT_LOCAL
            REAL(EB), SHARED :: DT_SHARED(HT1D_THREADS)

            LINE = BLOCKIDX%X
            TID = THREADIDX%X
            DT_LOCAL = HUGE(1._EB)
            IF (LINE>=1 .AND. LINE<=N_LINES .AND. CHECK_FO_IN/=0) THEN
                BASE = NODE_OFFSET_D(LINE)
                NWP = NWP_D(LINE)
                DO I=TID,NWP,BLOCKDIM%X
                    IDX = BASE + I
                    IF (K_S_D(IDX)>TWENTY_EPSILON_EB .AND. RHO_C_S_D(IDX)>TWENTY_EPSILON_EB) &
                        DT_LOCAL = MIN(DT_LOCAL,DX_D(IDX)**2*RHO_C_S_D(IDX)/K_S_D(IDX))
                ENDDO
            ENDIF

            DT_SHARED(TID) = DT_LOCAL
            CALL SYNCTHREADS()
            OFFSET = BLOCKDIM%X/2
            DO WHILE (OFFSET>=1)
                IF (TID<=OFFSET) DT_SHARED(TID) = MIN(DT_SHARED(TID),DT_SHARED(TID+OFFSET))
                CALL SYNCTHREADS()
                OFFSET = OFFSET/2
            ENDDO
            IF (TID==1 .AND. LINE>=1 .AND. LINE<=N_LINES) DT_FO_D(LINE) = DT_SHARED(1)
        END SUBROUTINE HT1D_BUILD_FO_LIMIT_GPU


        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_SELECT_SUBSTEP_BATCH_GPU(N_LINES,NODE_OFFSET_D,NWP_D,COEFF_VALID_D,Q_S_D, &
            RHO_C_S_D,DT_FO_D,T_BC_SUB_D,DT_SUB_D,LINE_ACTIVE_D,DT_BC,DELTA_TMP_MAX_D,TIME_STEP_FACTOR_D, &
            WALL_INCREMENT,TWO_EPS_D,USE_FO,ADAPT_SUBSTEP, &
            Q_IR_D,TMP_D,K_S_D,RDX_D,RDXN_D,INT_RAD_D,BACKING_D,H_FIXED_B_D,TMP_F_D,TMP_G_F_D,HTCF_D,Q_RAD_IN_F_D, &
            EMISSIVITY_F_D,TMP_B_D,TMP_G_B_D,HTCB_D,Q_RAD_IN_B_D,EMISSIVITY_B_D)
            ! Sub-time step of SOLID_HEAT_TRANSFER (FDS 6.11.1): the explicit temperature change over DT_BC from
            ! conduction, the net boundary fluxes and the volumetric sources, relative to DELTA_TMP_MAX.
            INTEGER, VALUE :: N_LINES,WALL_INCREMENT,USE_FO,ADAPT_SUBSTEP
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*),LINE_ACTIVE_D(*)
            REAL(EB), DEVICE :: Q_S_D(*),RHO_C_S_D(*),DT_FO_D(*),T_BC_SUB_D(*),DT_SUB_D(*)
            REAL(EB), DEVICE :: DELTA_TMP_MAX_D(*),TIME_STEP_FACTOR_D(*)
            REAL(EB), VALUE :: DT_BC,TWO_EPS_D
            REAL(EB), DEVICE :: Q_IR_D(*),TMP_D(*),K_S_D(*),RDX_D(*),RDXN_D(*),H_FIXED_B_D(*)
            INTEGER, DEVICE :: INT_RAD_D(*),BACKING_D(*)
            REAL(EB), DEVICE :: TMP_F_D(*),TMP_G_F_D(*),HTCF_D(*),Q_RAD_IN_F_D(*),EMISSIVITY_F_D(*)
            REAL(EB), DEVICE :: TMP_B_D(*),TMP_G_B_D(*),HTCB_D(*),Q_RAD_IN_B_D(*),EMISSIVITY_B_D(*)

            INTEGER :: LINE,BASE,NWP,TID,I,IDX,NREDUCE,OFFSET
            REAL(EB) :: TMP_RATIO,DELTA_TMP,DT_SUB,DT_FO_USE,DELTA_TMP_MAX,Q_CON_F,Q_CON_B,Q_NET_F,Q_NET_B,HTCB,FLUX
            REAL(EB), SHARED :: MAX_RATIO(HT1D_THREADS)

            LINE = BLOCKIDX%X
            TID = THREADIDX%X
            TMP_RATIO = TWO_EPS_D
            IF (LINE>=1 .AND. LINE<=N_LINES .AND. ADAPT_SUBSTEP/=0) THEN
            IF (LINE_ACTIVE_D(LINE)/=0 .AND. COEFF_VALID_D(LINE)/=0) THEN
                BASE = NODE_OFFSET_D(LINE)
                NWP = NWP_D(LINE)
                DELTA_TMP_MAX = DELTA_TMP_MAX_D(LINE)
                IF (DELTA_TMP_MAX>TWO_EPS_D .AND. NWP>=1) THEN
                    Q_CON_F = HTCF_D(LINE)*(TMP_G_F_D(LINE)-TMP_F_D(LINE))
                    SELECT CASE(BACKING_D(LINE))
                        CASE(VOID)
                            HTCB = HTCB_D(LINE)
                            IF (H_FIXED_B_D(LINE)<0._EB) HTCB = 1.31_EB*ABS(TMP_G_B_D(LINE)-TMP_B_D(LINE))**ONTH
                            Q_CON_B = HTCB*(TMP_G_B_D(LINE)-TMP_B_D(LINE))
                        CASE(EXPOSED)
                            ! wall.f90 uses the front-side DTMP here
                            Q_CON_B = HTCB_D(LINE)*(TMP_G_F_D(LINE)-TMP_F_D(LINE))
                        CASE DEFAULT
                            Q_CON_B = 0._EB
                    END SELECT
                    IF (INT_RAD_D(LINE)/=0) THEN
                        Q_NET_F = Q_CON_F
                        Q_NET_B = Q_CON_B
                    ELSE
                        Q_NET_F = Q_RAD_IN_F_D(LINE) - EMISSIVITY_F_D(LINE)*SIGMA*TMP_F_D(LINE)**4 + Q_CON_F
                        Q_NET_B = Q_RAD_IN_B_D(LINE) - EMISSIVITY_B_D(LINE)*SIGMA*TMP_B_D(LINE)**4 + Q_CON_B
                    ENDIF
                    DO I=TID,NWP,BLOCKDIM%X
                        IDX = BASE + I
                        IF (RHO_C_S_D(IDX)>TWO_EPS_D) THEN
                            IF (I==NWP) THEN
                                FLUX = RDX_D(IDX)*(-Q_NET_B-K_S_D(IDX-1)*RDXN_D(IDX-1)*(TMP_D(IDX)-TMP_D(IDX-1)))
                            ELSEIF (I==1) THEN
                                FLUX = RDX_D(IDX)*(K_S_D(IDX)*RDXN_D(IDX)*(TMP_D(IDX+1)-TMP_D(IDX))+Q_NET_F)
                            ELSE
                                FLUX = RDX_D(IDX)*(K_S_D(IDX)*RDXN_D(IDX)*(TMP_D(IDX+1)-TMP_D(IDX)) - &
                                                   K_S_D(IDX-1)*RDXN_D(IDX-1)*(TMP_D(IDX)-TMP_D(IDX-1)))
                            ENDIF
                            DELTA_TMP = (DT_BC/RHO_C_S_D(IDX))*(FLUX + Q_S_D(IDX) + Q_IR_D(IDX))
                            TMP_RATIO = MAX(TMP_RATIO,ABS(DELTA_TMP)/DELTA_TMP_MAX)
                        ENDIF
                    ENDDO
                ENDIF
            ENDIF
            ENDIF

            MAX_RATIO(TID) = TMP_RATIO
            CALL SYNCTHREADS()
            OFFSET = BLOCKDIM%X/2
            DO WHILE (OFFSET>=1)
                IF (TID<=OFFSET) MAX_RATIO(TID) = MAX(MAX_RATIO(TID),MAX_RATIO(TID+OFFSET))
                CALL SYNCTHREADS()
                OFFSET = OFFSET/2
            ENDDO

            IF (TID==1 .AND. LINE>=1 .AND. LINE<=N_LINES .AND. LINE_ACTIVE_D(LINE)/=0 .AND. &
                COEFF_VALID_D(LINE)/=0) THEN
                NREDUCE = MAX(1,MIN(NINT(TIME_STEP_FACTOR_D(LINE)*REAL(WALL_INCREMENT,EB)), &
                    MAX(1,NINT(MAX_RATIO(1)))))
                DT_SUB = DT_BC/REAL(NREDUCE,EB)
                IF (USE_FO/=0) THEN
                    DT_FO_USE = DT_FO_D(LINE)
                ELSE
                    DT_FO_USE = HUGE(1._EB)
                ENDIF
                DT_SUB = MIN(DT_BC-T_BC_SUB_D(LINE),DT_SUB,DT_FO_USE)
                IF (ADAPT_SUBSTEP==0) DT_SUB = DT_BC-T_BC_SUB_D(LINE)
                DT_SUB_D(LINE) = MAX(0._EB,DT_SUB)
                IF (DT_SUB_D(LINE)<=TWO_EPS_D) THEN
                    LINE_ACTIVE_D(LINE) = 0
                    COEFF_VALID_D(LINE) = 0
                ENDIF
            ENDIF
        END SUBROUTINE HT1D_SELECT_SUBSTEP_BATCH_GPU


        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_BUILD_MATERIAL_PROPERTIES_GPU(N_LINES,NODE_OFFSET_D,NWP_D,MATL_OFFSET_D, &
            N_MATL_D,LAYER_INDEX_D,MATL_INDEX_D,MATL_COMP_OFFSET_D,MATL_COMP_RHO_D,MATL_LAYER_OFFSET_D,DENSITY_ADJUST_D, &
            PACKING_RATIO_D,MATL_RHO_S_D,MATL_K_S_D,MATL_C_S_D,TMP_D,DX_WGT_D,K_NODE_D,K_S_D,RHO_C_S_D,VALID_D,I_MAX_TEMP_IN)
            INTEGER, VALUE :: N_LINES,I_MAX_TEMP_IN
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),MATL_OFFSET_D(*),N_MATL_D(*)
            INTEGER, DEVICE :: LAYER_INDEX_D(*),MATL_INDEX_D(*),MATL_COMP_OFFSET_D(*),MATL_LAYER_OFFSET_D(*),VALID_D(*)
            REAL(EB), DEVICE :: MATL_COMP_RHO_D(*),DENSITY_ADJUST_D(*),PACKING_RATIO_D(*)
            REAL(EB), DEVICE :: MATL_RHO_S_D(*),MATL_K_S_D(0:I_MAX_TEMP_IN,1:*),MATL_C_S_D(0:I_MAX_TEMP_IN,1:*)
            REAL(EB), DEVICE :: TMP_D(*),DX_WGT_D(*),K_NODE_D(*),K_S_D(*),RHO_C_S_D(*)

            INTEGER :: LINE,BASE,NWP,NMATL,MATL_BASE,LAYER_BASE,I,M,ITMP,IDX,LOCAL_MATL,LAYER
            INTEGER :: COMP_BASE
            REAL(EB) :: RHO_COMP,RHO_ADJUSTED,VOLSUM,KSUM,RHOCSUM,PACKING

            LINE = BLOCKIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            NMATL = N_MATL_D(LINE)
            MATL_BASE = MATL_OFFSET_D(LINE)
            LAYER_BASE = MATL_LAYER_OFFSET_D(LINE)

            IF (VALID_D(LINE)/=0) THEN
                DO I=THREADIDX%X,NWP,BLOCKDIM%X
                    IDX = BASE + I
                    LAYER = MAX(1,LAYER_INDEX_D(IDX))
                    ITMP = MAX(0,MIN(I_MAX_TEMP_IN-1,INT(TMP_D(IDX))))
                    VOLSUM = 0._EB
                    KSUM = 0._EB
                    RHOCSUM = 0._EB
                    DO M=1,NMATL
                        LOCAL_MATL = MATL_INDEX_D(MATL_BASE+M-1)
                        COMP_BASE = MATL_COMP_OFFSET_D(MATL_BASE+M-1)
                        RHO_COMP = MATL_COMP_RHO_D(COMP_BASE+I)
                        IF (RHO_COMP<=TWENTY_EPSILON_EB) CYCLE
                        RHO_ADJUSTED = MATL_RHO_S_D(LOCAL_MATL)*DENSITY_ADJUST_D(LAYER_BASE+(LAYER-1)*NMATL+M-1)
                        VOLSUM = VOLSUM + RHO_COMP/RHO_ADJUSTED
                        KSUM = KSUM + RHO_COMP*MATL_K_S_D(ITMP,LOCAL_MATL)/RHO_ADJUSTED
                        RHOCSUM = RHOCSUM + RHO_COMP*MATL_C_S_D(ITMP,LOCAL_MATL)
                    ENDDO
                    PACKING = PACKING_RATIO_D(IDX)
                    IF (PACKING>0._EB) KSUM = KSUM*PACKING
                    IF (VOLSUM>0._EB) KSUM = KSUM/VOLSUM
                    IF (KSUM<=TWENTY_EPSILON_EB) KSUM = 10000._EB
                    IF (RHOCSUM<=TWENTY_EPSILON_EB) RHOCSUM = 0.001_EB
                    K_NODE_D(IDX) = KSUM
                    RHO_C_S_D(IDX) = RHOCSUM
                ENDDO
            ENDIF

            CALL SYNCTHREADS()
            IF (THREADIDX%X==1 .AND. VALID_D(LINE)/=0 .AND. NWP>0) THEN
                K_S_D(BASE) = K_NODE_D(BASE+1)
                K_S_D(BASE+NWP) = K_NODE_D(BASE+NWP)
                K_S_D(BASE+NWP+1) = K_NODE_D(BASE+NWP)
                DO I=1,NWP-1
                    IDX = BASE + I
                    K_S_D(IDX) = 1._EB/(DX_WGT_D(IDX)/K_NODE_D(IDX)+ &
                        (1._EB-DX_WGT_D(IDX))/K_NODE_D(IDX+1))
                ENDDO
            ENDIF
        END SUBROUTINE HT1D_BUILD_MATERIAL_PROPERTIES_GPU



        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_BUILD_INTERIOR_COEFFICIENTS_BATCH_GPU(N_LINES,NODE_OFFSET_D,NWP_D, &
            COEFF_VALID_D,K_S_D,RHO_C_S_D,Q_S_D,TMP_D,RDX_D,RDXN_D,DT_SUB_D,AAS_D,BBS_D,DDS_D,CCS_D,DDT_D,Q_IR_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*)
            REAL(EB), DEVICE :: K_S_D(*),RHO_C_S_D(*),Q_S_D(*),TMP_D(*),RDX_D(*),RDXN_D(*),DT_SUB_D(*),Q_IR_D(*)
            REAL(EB), DEVICE :: AAS_D(*),BBS_D(*),DDS_D(*),CCS_D(*),DDT_D(*)

            INTEGER :: LINE,BASE,NWP,I,IDX
            REAL(EB) :: DT_SUB

            LINE = BLOCKIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. COEFF_VALID_D(LINE)==0) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            DT_SUB = DT_SUB_D(LINE)

            ! Interior nodes are independent. A block owns one complete wall
            ! line; strided threads cover lines longer than the block size.
            DO I=THREADIDX%X,NWP,BLOCKDIM%X
                IDX = BASE + I
                BBS_D(IDX) = -0.5_EB*DT_SUB*K_S_D(BASE+I-1)*RDXN_D(BASE+I-1)*RDX_D(BASE+I)/RHO_C_S_D(IDX)
                AAS_D(IDX) = -0.5_EB*DT_SUB*K_S_D(BASE+I)*RDXN_D(BASE+I)*RDX_D(BASE+I)/RHO_C_S_D(IDX)
                DDS_D(IDX) = 1._EB-AAS_D(IDX)-BBS_D(IDX)
                CCS_D(IDX) = TMP_D(IDX)-AAS_D(IDX)*(TMP_D(BASE+I+1)-TMP_D(IDX)) + &
                    BBS_D(IDX)*(TMP_D(IDX)-TMP_D(BASE+I-1)) + DT_SUB*(Q_S_D(IDX)+Q_IR_D(IDX))/RHO_C_S_D(IDX)
                DDT_D(IDX) = DDS_D(IDX)
            ENDDO
        END SUBROUTINE HT1D_BUILD_INTERIOR_COEFFICIENTS_BATCH_GPU



        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_CLOSE_BOUNDARIES_BATCH_GPU(N_LINES,NODE_OFFSET_D,NWP_D,COEFF_VALID_D, &
            K_S_D,TMP_D,DXF_D,DXB_D,HTCF_D,HTCB_D,TMP_G_F_D,TMP_G_B_D,TMP_F_D,TMP_B_D,Q_LIQUID_F_D, &
            Q_LIQUID_B_D,Q_RAD_IN_F_D,Q_RAD_IN_B_D,EMISSIVITY_F_D,EMISSIVITY_B_D,RAD_FRONT_D,RAD_BACK_D, &
            DIR_FRONT_D,DIR_BACK_D,AAS_D,BBS_D,CCS_D,DDT_D,RFACF2_D,QDXKF_D,RFACB2_D,QDXKB_D,BACKING_D,H_FIXED_B_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*)
            INTEGER, DEVICE :: RAD_FRONT_D(*),RAD_BACK_D(*),DIR_FRONT_D(*),DIR_BACK_D(*)
            REAL(EB), DEVICE :: K_S_D(*),TMP_D(*),DXF_D(*),DXB_D(*),HTCF_D(*),HTCB_D(*)
            REAL(EB), DEVICE :: TMP_G_F_D(*),TMP_G_B_D(*),TMP_F_D(*),TMP_B_D(*)
            REAL(EB), DEVICE :: Q_LIQUID_F_D(*),Q_LIQUID_B_D(*),Q_RAD_IN_F_D(*),Q_RAD_IN_B_D(*)
            REAL(EB), DEVICE :: EMISSIVITY_F_D(*),EMISSIVITY_B_D(*)
            REAL(EB), DEVICE :: AAS_D(*),BBS_D(*),CCS_D(*),DDT_D(*)
            REAL(EB), DEVICE :: RFACF2_D(*),QDXKF_D(*),RFACB2_D(*),QDXKB_D(*)
            INTEGER, DEVICE :: BACKING_D(*)
            REAL(EB), DEVICE :: H_FIXED_B_D(*)

            INTEGER :: LINE,BASE,NWP
            REAL(EB) :: KODXF,KODXB,RFACF,RFACB

            LINE = BLOCKIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. THREADIDX%X/=1) RETURN
            IF (COEFF_VALID_D(LINE)==0) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            IF (NWP<1) RETURN

            KODXF = K_S_D(BASE)/DXF_D(LINE)
            KODXB = K_S_D(BASE+NWP)/DXB_D(LINE)
            IF (BACKING_D(LINE)==VOID .AND. H_FIXED_B_D(LINE)<0._EB) &
                HTCB_D(LINE) = 1.31_EB*ABS(TMP_G_B_D(LINE)-TMP_B_D(LINE))**ONTH

            IF (DIR_FRONT_D(LINE)/=0) THEN
                RFACF2_D(LINE) = -1._EB
                QDXKF_D(LINE) = 2._EB*TMP_F_D(LINE)
            ELSEIF (RAD_FRONT_D(LINE)==0) THEN
                RFACF = 0.5_EB*HTCF_D(LINE)
                RFACF2_D(LINE) = (KODXF-RFACF)/(KODXF+RFACF)
                QDXKF_D(LINE) = (HTCF_D(LINE)*TMP_G_F_D(LINE)+Q_LIQUID_F_D(LINE))/(KODXF+RFACF)
            ELSE
                RFACF = 0.5_EB*HTCF_D(LINE)+2._EB*EMISSIVITY_F_D(LINE)*SIGMA*TMP_F_D(LINE)**3
                RFACF2_D(LINE) = (KODXF-RFACF)/(KODXF+RFACF)
                QDXKF_D(LINE) = (HTCF_D(LINE)*TMP_G_F_D(LINE)+Q_LIQUID_F_D(LINE)+Q_RAD_IN_F_D(LINE)+ &
                    3._EB*EMISSIVITY_F_D(LINE)*SIGMA*TMP_F_D(LINE)**4)/(KODXF+RFACF)
            ENDIF

            IF (DIR_BACK_D(LINE)/=0) THEN
                RFACB2_D(LINE) = -1._EB
                QDXKB_D(LINE) = 2._EB*TMP_B_D(LINE)
            ELSEIF (RAD_BACK_D(LINE)==0) THEN
                RFACB = 0.5_EB*HTCB_D(LINE)
                RFACB2_D(LINE) = (KODXB-RFACB)/(KODXB+RFACB)
                QDXKB_D(LINE) = (HTCB_D(LINE)*TMP_G_B_D(LINE)+Q_LIQUID_B_D(LINE))/(KODXB+RFACB)
            ELSE
                RFACB = 0.5_EB*HTCB_D(LINE)+2._EB*EMISSIVITY_B_D(LINE)*SIGMA*TMP_B_D(LINE)**3
                RFACB2_D(LINE) = (KODXB-RFACB)/(KODXB+RFACB)
                QDXKB_D(LINE) = (HTCB_D(LINE)*TMP_G_B_D(LINE)+Q_LIQUID_B_D(LINE)+Q_RAD_IN_B_D(LINE)+ &
                    3._EB*EMISSIVITY_B_D(LINE)*SIGMA*TMP_B_D(LINE)**4)/(KODXB+RFACB)
            ENDIF

            CCS_D(BASE+1) = CCS_D(BASE+1)-BBS_D(BASE+1)*QDXKF_D(LINE)
            CCS_D(BASE+NWP) = CCS_D(BASE+NWP)-AAS_D(BASE+NWP)*QDXKB_D(LINE)
            DDT_D(BASE+1) = DDT_D(BASE+1)+BBS_D(BASE+1)*RFACF2_D(LINE)
            DDT_D(BASE+NWP) = DDT_D(BASE+NWP)+AAS_D(BASE+NWP)*RFACB2_D(LINE)
        END SUBROUTINE HT1D_CLOSE_BOUNDARIES_BATCH_GPU

        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_THOMAS_SOLVE_BATCH_GPU(N_LINES,NODE_OFFSET_D,NWP_D,COEFF_VALID_D,AAS_D, &
            BBS_D,CCS_D,DDT_D,TMPMIN_IN,TMPMAX_IN)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*)
            REAL(EB), DEVICE :: AAS_D(*),BBS_D(*),CCS_D(*),DDT_D(*)
            REAL(EB), VALUE :: TMPMIN_IN,TMPMAX_IN

            INTEGER :: LINE,BASE,NWP,I,IDX
            REAL(EB) :: RR

            LINE = BLOCKIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. THREADIDX%X/=1) RETURN
            IF (COEFF_VALID_D(LINE)==0) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)

            DO I=2,NWP
                IDX = BASE + I
                RR = BBS_D(IDX)/DDT_D(IDX-1)
                DDT_D(IDX) = DDT_D(IDX) - RR*AAS_D(IDX-1)
                CCS_D(IDX) = CCS_D(IDX) - RR*CCS_D(IDX-1)
            ENDDO
            IDX = BASE + NWP
            CCS_D(IDX) = CCS_D(IDX)/DDT_D(IDX)
            DO I=NWP-1,1,-1
                IDX = BASE + I
                CCS_D(IDX) = (CCS_D(IDX)-AAS_D(IDX)*CCS_D(IDX+1))/DDT_D(IDX)
            ENDDO
            DO I=1,NWP
                IDX = BASE + I
                CCS_D(IDX) = MIN(TMPMAX_IN,MAX(TMPMIN_IN,CCS_D(IDX)))
            ENDDO
        END SUBROUTINE HT1D_THOMAS_SOLVE_BATCH_GPU


        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_COMMIT_TEMPERATURE_BATCH_GPU(N_LINES,NODE_OFFSET_D,NWP_D,CCS_D,TMP_D, &
            RFACF2_D,QDXKF_D,RFACB2_D,QDXKB_D,STATE_VALID_D,TMPMIN_IN,TMPMAX_IN)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),STATE_VALID_D(*)
            REAL(EB), VALUE :: TMPMIN_IN,TMPMAX_IN
            REAL(EB), DEVICE :: CCS_D(*),TMP_D(*),RFACF2_D(*),QDXKF_D(*),RFACB2_D(*),QDXKB_D(*)

            INTEGER :: LINE,TID,I,BASE,NWP

            LINE = BLOCKIDX%X
            TID = THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES .OR. STATE_VALID_D(LINE)==0) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)

            DO I=TID,NWP,BLOCKDIM%X
                TMP_D(BASE+I) = MIN(TMPMAX_IN,MAX(TMPMIN_IN,CCS_D(BASE+I)))
            ENDDO
            CALL SYNCTHREADS()
            IF (TID==1) THEN
                TMP_D(BASE) = MAX(TMPMIN_IN,TMP_D(BASE+1)*RFACF2_D(LINE)+QDXKF_D(LINE))
                TMP_D(BASE+NWP+1) = MAX(TMPMIN_IN,TMP_D(BASE+NWP)*RFACB2_D(LINE)+QDXKB_D(LINE))
            ENDIF
        END SUBROUTINE HT1D_COMMIT_TEMPERATURE_BATCH_GPU

        !> Internal radiation of SOLID_HEAT_TRANSFER (two-flux model, Cartesian), one thread per line: the source Q_IR
        !> of the current temperatures and the emitted flux Q_RAD_OUT of this sub-time step.
        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_INTERNAL_RADIATION_GPU(N_LINES,NODE_OFFSET_D,NWP_D,COEFF_VALID_D, &
            INT_RAD_D,TWO_DX_KAPPA_D,TMP_D,RDX_D,Q_RAD_IN_F_D,EMISSIVITY_F_D,Q_RAD_IN_B_D,EMISSIVITY_B_D, &
            Q_RAD_OUT_OLD_D,Q_RAD_OUT_SUB_D,Q_IR_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: NODE_OFFSET_D(*),NWP_D(*),COEFF_VALID_D(*),INT_RAD_D(*)
            REAL(EB), DEVICE :: TWO_DX_KAPPA_D(*),TMP_D(*),RDX_D(*),Q_RAD_IN_F_D(*),EMISSIVITY_F_D(*)
            REAL(EB), DEVICE :: Q_RAD_IN_B_D(*),EMISSIVITY_B_D(*),Q_RAD_OUT_OLD_D(*),Q_RAD_OUT_SUB_D(*),Q_IR_D(*)

            INTEGER :: LINE,BASE,NWP,I,IDX
            REAL(EB) :: RFLUX_UP,RFLUX_DOWN

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            IF (COEFF_VALID_D(LINE)==0 .OR. INT_RAD_D(LINE)==0) RETURN
            BASE = NODE_OFFSET_D(LINE)
            NWP = NWP_D(LINE)
            IF (NWP<1) RETURN

            ! solution inwards
            RFLUX_UP = Q_RAD_IN_F_D(LINE) + (1._EB-EMISSIVITY_F_D(LINE))*Q_RAD_OUT_OLD_D(LINE)/(EMISSIVITY_F_D(LINE)+1.0E-10_EB)
            RFLUX_DOWN = RFLUX_UP
            DO I=1,NWP
                IDX = BASE + I
                RFLUX_DOWN = (RFLUX_UP + TWO_DX_KAPPA_D(IDX)*SIGMA*TMP_D(IDX)**4)/(1._EB + TWO_DX_KAPPA_D(IDX))
                Q_IR_D(IDX) = (RFLUX_UP - RFLUX_DOWN)*RDX_D(IDX)
                RFLUX_UP = RFLUX_DOWN
            ENDDO
            ! solution outwards
            RFLUX_UP = Q_RAD_IN_B_D(LINE) + (1._EB-EMISSIVITY_B_D(LINE))*RFLUX_UP
            DO I=NWP,1,-1
                IDX = BASE + I
                RFLUX_DOWN = (RFLUX_UP + TWO_DX_KAPPA_D(IDX)*SIGMA*TMP_D(IDX)**4)/(1._EB + TWO_DX_KAPPA_D(IDX))
                Q_IR_D(IDX) = Q_IR_D(IDX) + (RFLUX_UP - RFLUX_DOWN)*RDX_D(IDX)
                RFLUX_UP = RFLUX_DOWN
            ENDDO
            Q_RAD_OUT_SUB_D(LINE) = EMISSIVITY_F_D(LINE)*RFLUX_DOWN
        END SUBROUTINE HT1D_INTERNAL_RADIATION_GPU

        !> Count the lines still active after a sub-time step.
        ATTRIBUTES(GLOBAL) SUBROUTINE HT1D_COUNT_ACTIVE_GPU(N_LINES,LINE_ACTIVE_D,COUNT_D)
            INTEGER, VALUE :: N_LINES
            INTEGER, DEVICE :: LINE_ACTIVE_D(*),COUNT_D(*)
            INTEGER :: LINE,ISTAT

            LINE = (BLOCKIDX%X-1)*BLOCKDIM%X + THREADIDX%X
            IF (LINE<1 .OR. LINE>N_LINES) RETURN
            IF (LINE_ACTIVE_D(LINE)/=0) ISTAT = ATOMICADD(COUNT_D(1),1)
        END SUBROUTINE HT1D_COUNT_ACTIVE_GPU

