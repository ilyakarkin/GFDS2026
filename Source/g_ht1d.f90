        SUBROUTINE GET_HT1D_LINE_SIZE(NM,IW,ELIGIBLE,NWP,NMATL,REASON)
            INTEGER, INTENT(IN) :: NM,IW
            LOGICAL, INTENT(OUT) :: ELIGIBLE
            INTEGER, INTENT(OUT) :: NWP,NMATL
            CHARACTER(*), INTENT(OUT), OPTIONAL :: REASON   ! why the WALL cell has no device line (for the refusal)

            TYPE(MESH_TYPE), POINTER :: M
            TYPE(WALL_TYPE), POINTER :: WC
            TYPE(BOUNDARY_ONE_D_TYPE), POINTER :: ONE_D
            TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
            TYPE(SURFACE_TYPE), POINTER :: SF

            ELIGIBLE = .FALSE.
            NWP = 0
            NMATL = 0
            IF (PRESENT(REASON)) REASON = 'the wall state'
            M => MESHES(NM)

            IF (IW<1 .OR. IW>M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS) RETURN
            WC => M%WALL(IW)
            IF (WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) RETURN
            IF (WC%OD_INDEX<1 .OR. .NOT.ALLOCATED(M%BOUNDARY_ONE_D)) RETURN
            IF (WC%OD_INDEX>SIZE(M%BOUNDARY_ONE_D)) RETURN
            IF (WC%BC_INDEX<1 .OR. .NOT.ALLOCATED(M%BOUNDARY_COORD)) RETURN
            IF (WC%BC_INDEX>SIZE(M%BOUNDARY_COORD)) RETURN
            IF (WC%SURF_INDEX<1 .OR. WC%SURF_INDEX>SIZE(SURFACE)) RETURN
            BC => M%BOUNDARY_COORD(WC%BC_INDEX)
            SF => SURFACE(WC%SURF_INDEX)
            IF (SF%THERMAL_BC_INDEX/=THERMALLY_THICK) RETURN

            ! Cartesian conduction with optional prescribed burning. VARIABLE_THICKNESS: the WALL cell has its own
            ! noding (ONE_D%X); without solid-phase reactions it does not change in time (COMPUTE_GRID in wall.f90).
            IF (PRESENT(REASON)) REASON = 'GEOMETRY other than CARTESIAN or HT3D'
            IF (SF%GEOMETRY/=SURF_CARTESIAN .OR. SF%HT_DIM/=1) RETURN
            ! TMP_BACK (DIRICHLET_BACK) is applied on the device for VOID backing, as in wall.f90; TMP_FRONT is not.
            IF (PRESENT(REASON)) REASON = 'TMP_FRONT'
            IF (SF%DIRICHLET_FRONT) RETURN
            IF (PRESENT(REASON)) REASON = 'HEAT_TRANSFER_MODEL'
            IF (SF%H_FIXED<0._EB .AND. SF%HEAT_TRANSFER_MODEL/=DEFAULT_HTC_MODEL) RETURN
            ONE_D => M%BOUNDARY_ONE_D(WC%OD_INDEX)
            IF (PRESENT(REASON)) REASON = 'solid-phase pyrolysis'
            IF (ONE_D%PYROLYSIS_MODEL/=PYROLYSIS_NONE .AND. ONE_D%PYROLYSIS_MODEL/=PYROLYSIS_SPECIFIED) RETURN
            IF (PRESENT(REASON)) REASON = 'a specified burning rate with SOLID_PHASE_ONLY'
            IF (ONE_D%PYROLYSIS_MODEL==PYROLYSIS_SPECIFIED .AND. SOLID_PHASE_ONLY .AND. .NOT.SF%INERT_Q_REF) RETURN
            IF (PRESENT(REASON)) REASON = 'particles generated by the surface or BOUNDARY_FUEL_MODEL'
            IF (ONE_D%N_LPC>0 .OR. SF%N_LPC>0 .OR. SF%BOUNDARY_FUEL_MODEL) RETURN
            IF (PRESENT(REASON)) REASON = 'HVAC or aerosol deposition'
            IF (HVAC_SOLVE .OR. DEPOSITION) RETURN
            ! Liquid droplets on the surface: the heat they take, -SUM(B2%LP_CPUA), comes from the host particle code
            ! (HT1D_SET_LIQUID_GPU). The host has the running averages of the back side only if its mesh is local.
            IF (PRESENT(REASON)) REASON = 'liquid droplets with the EXPOSED back side in a mesh of another MPI process'
            IF (LIQUID_DROPLETS .AND. SF%BACKING==EXPOSED .AND. ONE_D%BACK_INDEX>0) THEN
                IF (ONE_D%BACK_MESH<1 .OR. ONE_D%BACK_MESH>NMESHES) RETURN
                IF (PROCESS(ONE_D%BACK_MESH)/=MY_RANK) RETURN
            ENDIF
            IF (PRESENT(REASON)) REASON = 'a RAMP of the internal heat source'
            IF (ALLOCATED(ONE_D%HEAT_SOURCE)) THEN
                IF (ANY(ABS(ONE_D%HEAT_SOURCE(1:ONE_D%N_LAYERS))>TWENTY_EPSILON_EB)) THEN
                    ! The device substep uses constant volumetric sources.
                    IF (.NOT.ALLOCATED(ONE_D%RAMP_IHS_INDEX)) RETURN
                    IF (ANY(ONE_D%RAMP_IHS_INDEX(1:ONE_D%N_LAYERS)/=0)) RETURN
                ENDIF
            ENDIF
            IF (PRESENT(REASON)) REASON = 'MASS_FLUX without a specified burning rate'
            IF (ALLOCATED(SF%MASS_FLUX)) THEN
                IF (ANY(ABS(SF%MASS_FLUX)>TWENTY_EPSILON_EB) .AND. ONE_D%PYROLYSIS_MODEL/=PYROLYSIS_SPECIFIED) RETURN
            ENDIF
            IF (PRESENT(REASON)) REASON = 'the wall state'
            IF (ONE_D%N_LAYERS<1 .OR. .NOT.ALLOCATED(ONE_D%N_LAYER_CELLS)) RETURN

            NWP = SUM(ONE_D%N_LAYER_CELLS(1:ONE_D%N_LAYERS))
            NMATL = ONE_D%N_MATL
            IF (NWP<1 .OR. NMATL<1) RETURN
            IF (.NOT.ALLOCATED(ONE_D%X) .OR. .NOT.ALLOCATED(ONE_D%TMP)) RETURN
            IF (.NOT.ALLOCATED(ONE_D%MATL_INDEX)) RETURN
            IF (UBOUND(ONE_D%X,1)<NWP .OR. UBOUND(ONE_D%TMP,1)<NWP+1) RETURN
            IF (SIZE(ONE_D%MATL_INDEX)<NMATL) RETURN

            IF (SF%VARIABLE_THICKNESS) THEN
                IF (.NOT.ALLOCATED(ONE_D%LAYER_THICKNESS)) RETURN
                IF (SIZE(ONE_D%LAYER_THICKNESS)<ONE_D%N_LAYERS .OR. SIZE(ONE_D%N_LAYER_CELLS)<ONE_D%N_LAYERS) RETURN
            ELSE
                IF (.NOT.ALLOCATED(SF%DX) .OR. .NOT.ALLOCATED(SF%RDX) .OR. &
                    .NOT.ALLOCATED(SF%RDXN) .OR. .NOT.ALLOCATED(SF%DX_WGT) .OR. &
                    .NOT.ALLOCATED(SF%LAYER_INDEX)) RETURN
                IF (UBOUND(SF%DX,1)<NWP .OR. UBOUND(SF%RDX,1)<NWP+1 .OR. &
                    UBOUND(SF%RDXN,1)<NWP .OR. UBOUND(SF%DX_WGT,1)<NWP .OR. &
                    UBOUND(SF%LAYER_INDEX,1)<NWP+1) RETURN
            ENDIF

            ELIGIBLE = .TRUE.
            IF (PRESENT(REASON)) REASON = ''
        END SUBROUTINE GET_HT1D_LINE_SIZE

        SUBROUTINE INITIALIZE_GPU_HT1D(NM)
            INTEGER, INTENT(IN) :: NM
            INTEGER :: IW,IL,I,J,NWP,NMATL,BASE,NODE_TOTAL,MATL_TOTAL,COMP_TOTAL,MATL_LAYER_TOTAL
            INTEGER :: ITMP
            INTEGER :: GLOBAL_MATL,LOCAL_MATL,NL
            INTEGER :: SLOT
            LOGICAL :: ELIGIBLE,STATIC_TABLE
            TYPE(MESH_TYPE), POINTER :: M
            TYPE(WALL_TYPE), POINTER :: WC
            TYPE(BOUNDARY_ONE_D_TYPE), POINTER :: ONE_D
            TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
            TYPE(SURFACE_TYPE), POINTER :: SF
            TYPE(GPU_MESH_TYPE), POINTER :: GM

            INTEGER, ALLOCATABLE :: WALL_INDEX_H(:),OD_INDEX_H(:),B1_INDEX_H(:),BC_INDEX_H(:)
            INTEGER, ALLOCATABLE :: SURF_INDEX_H(:),IEC_H(:),IOR_H(:),BACK_INDEX_H(:),BACK_MESH_H(:)
            INTEGER, ALLOCATABLE :: NODE_OFFSET_H(:),NWP_H(:)
            INTEGER, ALLOCATABLE :: MATL_OFFSET_H(:),N_MATL_H(:),LAYER_INDEX_H(:),MATL_INDEX_H(:),MATL_GLOBAL_INDEX_H(:)
            INTEGER, ALLOCATABLE :: MATL_COMP_OFFSET_H(:),MATL_LAYER_OFFSET_H(:),N_LAYERS_H(:)
            INTEGER, ALLOCATABLE :: UNIQUE_MATL_H(:)
            REAL(EB), ALLOCATABLE :: X_H(:),DX_H(:),RDX_H(:),RDXN_H(:),DX_WGT_H(:),TMP_H(:)
            REAL(EB), ALLOCATABLE :: MATL_COMP_RHO_H(:),DENSITY_ADJUST_H(:),PACKING_RATIO_H(:)
            REAL(EB), ALLOCATABLE :: MATL_RHO_S_H(:),MATL_K_S_H(:,:),MATL_C_S_H(:,:)
            REAL(EB), ALLOCATABLE :: TIME_STEP_FACTOR_H(:),DELTA_TMP_MAX_H(:)
            REAL(EB), ALLOCATABLE :: H_FIXED_B_H(:),TMP_G_BACK_H(:),EMISSIVITY_B_H(:)
            INTEGER, ALLOCATABLE :: RAMP_H_FIXED_B_H(:),RAMP_TMP_G_BACK_H(:),RAMP_TB_H(:)
            REAL(EB), ALLOCATABLE :: TMP_BACK_H(:)
            INTEGER, ALLOCATABLE :: LI_W(:)
            REAL(EB), ALLOCATABLE :: DX_W(:),RDX_W(:),RDXN_W(:),DX_WGT_W(:),MF_FRAC_W(:)
            REAL(EB) :: DXF_W,DXB_W,X_DIVIDE_W
            INTEGER, ALLOCATABLE :: INT_RAD_H(:)
            REAL(EB), ALLOCATABLE :: TWO_DX_KAPPA_H(:)
            REAL(EB) :: VOLSUM,KAPSUM,RHO_ADJ
            INTEGER :: LI

            M => MESHES(NM)
            GM => GPU_MESHES(NM)
            IF (GM%HT1D_INITIALIZED) RETURN

            GM%HT1D_N_LINES = 0
            GM%HT1D_N_NODES = 0
            GM%HT1D_N_MATL_TOTAL = 0
            GM%HT1D_N_FALLBACK = M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
            GM%HT1D_INITIALIZED = .TRUE.

            IF (GM%HT1D_N_FALLBACK<=0) RETURN

            ! First pass determines compact sizes. Node arrays share one offset;
            ! local indices 0:NWP+1 are stored at BASE+0:BASE+NWP+1.
            NODE_TOTAL = 0
            MATL_TOTAL = 0
            COMP_TOTAL = 0
            MATL_LAYER_TOTAL = 0
            GM%HT1D_MAX_SUBSTEPS = 1
            DO IW=1,GM%HT1D_N_FALLBACK
                CALL GET_HT1D_LINE_SIZE(NM,IW,ELIGIBLE,NWP,NMATL)
                IF (.NOT.ELIGIBLE) CYCLE
                ONE_D => M%BOUNDARY_ONE_D(M%WALL(IW)%OD_INDEX)
                SF => SURFACE(M%WALL(IW)%SURF_INDEX)
                GM%HT1D_N_LINES = GM%HT1D_N_LINES + 1
                NODE_TOTAL = NODE_TOTAL + NWP + 2
                MATL_TOTAL = MATL_TOTAL + NMATL
                COMP_TOTAL = COMP_TOTAL + NMATL*(NWP+2)
                MATL_LAYER_TOTAL = MATL_LAYER_TOTAL + NMATL*ONE_D%N_LAYERS
                ! The sub-time step is DT_BC/N with N<=TIME_STEP_FACTOR*WALL_INCREMENT (wall.f90). The loop over
                ! substeps ends early once no line is active.
                GM%HT1D_MAX_SUBSTEPS = MAX(GM%HT1D_MAX_SUBSTEPS, &
                    MAX(1,NINT(SF%TIME_STEP_FACTOR*REAL(WALL_INCREMENT,EB)))+1)
            ENDDO
            GM%HT1D_N_NODES = NODE_TOTAL
            GM%HT1D_N_MATL_TOTAL = MATL_TOTAL
            GM%HT1D_N_MATL_COMP_VALUES = COMP_TOTAL
            GM%HT1D_N_MATL_LAYER_VALUES = MATL_LAYER_TOTAL
            GM%HT1D_N_FALLBACK = M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS-GM%HT1D_N_LINES

            IF (GM%HT1D_N_LINES<=0) RETURN

            ALLOCATE(WALL_INDEX_H(1:GM%HT1D_N_LINES),OD_INDEX_H(1:GM%HT1D_N_LINES))
            ALLOCATE(B1_INDEX_H(1:GM%HT1D_N_LINES),BC_INDEX_H(1:GM%HT1D_N_LINES))
            ALLOCATE(SURF_INDEX_H(1:GM%HT1D_N_LINES),IEC_H(1:GM%HT1D_N_LINES),IOR_H(1:GM%HT1D_N_LINES))
            ALLOCATE(BACK_INDEX_H(1:GM%HT1D_N_LINES),BACK_MESH_H(1:GM%HT1D_N_LINES))
            ALLOCATE(NODE_OFFSET_H(1:GM%HT1D_N_LINES),NWP_H(1:GM%HT1D_N_LINES))
            ALLOCATE(MATL_OFFSET_H(1:GM%HT1D_N_LINES),N_MATL_H(1:GM%HT1D_N_LINES))
            ALLOCATE(MATL_LAYER_OFFSET_H(1:GM%HT1D_N_LINES),N_LAYERS_H(1:GM%HT1D_N_LINES))
            ALLOCATE(LAYER_INDEX_H(1:GM%HT1D_N_NODES),X_H(1:GM%HT1D_N_NODES))
            ALLOCATE(DX_H(1:GM%HT1D_N_NODES),RDX_H(1:GM%HT1D_N_NODES))
            ALLOCATE(RDXN_H(1:GM%HT1D_N_NODES),DX_WGT_H(1:GM%HT1D_N_NODES))
            ALLOCATE(TMP_H(1:GM%HT1D_N_NODES),MATL_INDEX_H(1:GM%HT1D_N_MATL_TOTAL))
            ALLOCATE(MATL_GLOBAL_INDEX_H(1:GM%HT1D_N_MATL_TOTAL),MATL_COMP_OFFSET_H(1:GM%HT1D_N_MATL_TOTAL))
            ALLOCATE(UNIQUE_MATL_H(1:GM%HT1D_N_MATL_TOTAL))
            ALLOCATE(MATL_COMP_RHO_H(1:GM%HT1D_N_MATL_COMP_VALUES),DENSITY_ADJUST_H(1:GM%HT1D_N_MATL_LAYER_VALUES))
            ALLOCATE(PACKING_RATIO_H(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_WALL_TO_LINE_H(1:M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS))
            ALLOCATE(GM%HT1D_NODE_OFFSET_H(1:GM%HT1D_N_LINES),GM%HT1D_NWP_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACK_INDEX_H(1:GM%HT1D_N_LINES),GM%HT1D_BACK_MESH_H(1:GM%HT1D_N_LINES), &
                GM%HT1D_BACK_LINE_H(1:GM%HT1D_N_LINES),GM%HT1D_BACK_REMOTE_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACK_SLOT_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACKSIDE_VALID_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACKING_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_RAD_FRONT_H(1:GM%HT1D_N_LINES),GM%HT1D_RAD_BACK_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_DIRICHLET_FRONT_H(1:GM%HT1D_N_LINES),GM%HT1D_DIRICHLET_BACK_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TMP_H(1:GM%HT1D_N_NODES),GM%HT1D_Q_S_H(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_DXF_H(1:GM%HT1D_N_LINES),GM%HT1D_DXB_H(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TMP_B_H(1:GM%HT1D_N_LINES))
            ALLOCATE(TIME_STEP_FACTOR_H(1:GM%HT1D_N_LINES),DELTA_TMP_MAX_H(1:GM%HT1D_N_LINES))
            ALLOCATE(H_FIXED_B_H(GM%HT1D_N_LINES),TMP_G_BACK_H(GM%HT1D_N_LINES),EMISSIVITY_B_H(GM%HT1D_N_LINES))
            ALLOCATE(RAMP_H_FIXED_B_H(GM%HT1D_N_LINES),RAMP_TMP_G_BACK_H(GM%HT1D_N_LINES))
            ALLOCATE(RAMP_TB_H(GM%HT1D_N_LINES),TMP_BACK_H(GM%HT1D_N_LINES))
            ALLOCATE(INT_RAD_H(GM%HT1D_N_LINES),TWO_DX_KAPPA_H(GM%HT1D_N_NODES))
            INT_RAD_H = 0
            TWO_DX_KAPPA_H = 0._EB
            GM%HT1D_WALL_TO_LINE_H = 0
            GM%HT1D_BACK_INDEX_H = 0
            GM%HT1D_BACK_MESH_H = 0
            GM%HT1D_BACK_LINE_H = 0
            GM%HT1D_BACK_REMOTE_H = 0
            GM%HT1D_BACK_SLOT_H = 0
            GM%HT1D_BACKSIDE_VALID_H = 0
            GM%HT1D_BACKING_H = INSULATED
            TIME_STEP_FACTOR_H = 1._EB
            DELTA_TMP_MAX_H = 10._EB
            LAYER_INDEX_H = 0
            X_H = 0._EB
            DX_H = 0._EB
            RDX_H = 0._EB
            RDXN_H = 0._EB
            DX_WGT_H = 0._EB
            TMP_H = 0._EB
            MATL_INDEX_H = 0
            MATL_GLOBAL_INDEX_H = 0
            MATL_COMP_OFFSET_H = 0
            MATL_LAYER_OFFSET_H = 0
            N_LAYERS_H = 0
            UNIQUE_MATL_H = 0
            MATL_COMP_RHO_H = 0._EB
            DENSITY_ADJUST_H = 0._EB
            PACKING_RATIO_H = 1._EB

            IL = 0
            NODE_TOTAL = 0
            MATL_TOTAL = 0
            COMP_TOTAL = 0
            MATL_LAYER_TOTAL = 0
            GM%HT1D_N_UNIQUE_MATL = 0
            DO IW=1,GM%HT1D_N_FALLBACK+GM%HT1D_N_LINES
                CALL GET_HT1D_LINE_SIZE(NM,IW,ELIGIBLE,NWP,NMATL)
                IF (.NOT.ELIGIBLE) CYCLE
                IL = IL + 1
                WC => M%WALL(IW)
                ONE_D => M%BOUNDARY_ONE_D(WC%OD_INDEX)
                BC => M%BOUNDARY_COORD(WC%BC_INDEX)
                SF => SURFACE(WC%SURF_INDEX)

                WALL_INDEX_H(IL) = IW
                OD_INDEX_H(IL) = WC%OD_INDEX
                B1_INDEX_H(IL) = WC%B1_INDEX
                BC_INDEX_H(IL) = WC%BC_INDEX
                SURF_INDEX_H(IL) = WC%SURF_INDEX
                IEC_H(IL) = ABS(BC%IOR)
                IOR_H(IL) = BC%IOR
                BACK_INDEX_H(IL) = ONE_D%BACK_INDEX
                BACK_MESH_H(IL) = ONE_D%BACK_MESH
                NWP_H(IL) = NWP
                N_MATL_H(IL) = NMATL
                NODE_OFFSET_H(IL) = NODE_TOTAL + 1
                MATL_OFFSET_H(IL) = MATL_TOTAL + 1
                MATL_LAYER_OFFSET_H(IL) = MATL_LAYER_TOTAL + 1
                N_LAYERS_H(IL) = ONE_D%N_LAYERS
                BASE = NODE_OFFSET_H(IL)

                GM%HT1D_WALL_TO_LINE_H(IW) = IL
                GM%HT1D_NODE_OFFSET_H(IL) = NODE_OFFSET_H(IL)
                GM%HT1D_NWP_H(IL) = NWP
                GM%HT1D_BACK_INDEX_H(IL) = ONE_D%BACK_INDEX
                GM%HT1D_BACK_MESH_H(IL) = ONE_D%BACK_MESH
                GM%HT1D_BACK_REMOTE_H(IL) = MERGE(1,0,ONE_D%BACK_INDEX>0 .AND. ONE_D%BACK_MESH>0 .AND. ONE_D%BACK_MESH/=NM)
                GM%HT1D_BACKING_H(IL) = SF%BACKING
                IF (ONE_D%BACK_INDEX==0 .AND. GM%HT1D_BACKING_H(IL)==EXPOSED) GM%HT1D_BACKING_H(IL) = VOID
                H_FIXED_B_H(IL) = SF%H_FIXED_B
                TMP_G_BACK_H(IL) = SF%TMP_GAS_BACK
                RAMP_H_FIXED_B_H(IL) = SF%RAMP_H_FIXED_B_INDEX
                RAMP_TMP_G_BACK_H(IL) = SF%RAMP(TIME_TGB)%INDEX
                RAMP_TB_H(IL) = SF%RAMP(TIME_TB)%INDEX
                TMP_BACK_H(IL) = SF%TMP_BACK
                IF (SF%EMISSIVITY_BACK_SPECIFIED) THEN
                    EMISSIVITY_B_H(IL) = SF%EMISSIVITY_BACK
                ELSE
                    CALL GET_EMISSIVITY(ONE_D,NWP,EMISSIVITY_B_H(IL))
                ENDIF
                TIME_STEP_FACTOR_H(IL) = SF%TIME_STEP_FACTOR
                DELTA_TMP_MAX_H(IL) = SF%DELTA_TMP_MAX

                X_H(BASE:BASE+NWP) = ONE_D%X(0:NWP)
                TMP_H(BASE:BASE+NWP+1) = ONE_D%TMP(0:NWP+1)
                IF (SF%VARIABLE_THICKNESS) THEN
                    ! Noding of this WALL cell, as COMPUTE_GRID in SOLID_HEAT_TRANSFER
                    ALLOCATE(LI_W(0:NWP+1),DX_W(1:NWP),RDX_W(0:NWP+1),RDXN_W(0:NWP),DX_WGT_W(0:NWP),MF_FRAC_W(1:NWP))
                    CALL GET_WALL_NODE_WEIGHTS(NWP,ONE_D%N_LAYERS,ONE_D%N_LAYER_CELLS(1:ONE_D%N_LAYERS), &
                        ONE_D%LAYER_THICKNESS(1:ONE_D%N_LAYERS),SF%GEOMETRY,ONE_D%X(0:NWP),SF%LAYER_DIVIDE,DX_W,RDX_W, &
                        RDXN_W,DX_WGT_W,DXF_W,DXB_W,LI_W,MF_FRAC_W,SF%INNER_RADIUS,X_DIVIDE_W)
                    GM%HT1D_DXF_H(IL) = DXF_W
                    GM%HT1D_DXB_H(IL) = DXB_W
                    LAYER_INDEX_H(BASE:BASE+NWP+1) = LI_W(0:NWP+1)
                    DX_H(BASE+1:BASE+NWP) = DX_W(1:NWP)
                    RDX_H(BASE:BASE+NWP+1) = RDX_W(0:NWP+1)
                    RDXN_H(BASE:BASE+NWP) = RDXN_W(0:NWP)
                    DX_WGT_H(BASE:BASE+NWP) = DX_WGT_W(0:NWP)
                    DEALLOCATE(LI_W,DX_W,RDX_W,RDXN_W,DX_WGT_W,MF_FRAC_W)
                ELSE
                    GM%HT1D_DXF_H(IL) = SF%DXF
                    GM%HT1D_DXB_H(IL) = SF%DXB
                    LAYER_INDEX_H(BASE:BASE+NWP+1) = SF%LAYER_INDEX(0:NWP+1)
                    DO I=1,NWP
                        DX_H(BASE+I) = SF%DX(I)
                    ENDDO
                    RDX_H(BASE:BASE+NWP+1) = SF%RDX(0:NWP+1)
                    RDXN_H(BASE:BASE+NWP) = SF%RDXN(0:NWP)
                    DX_WGT_H(BASE:BASE+NWP) = SF%DX_WGT(0:NWP)
                ENDIF
                IF (ONE_D%INTERNAL_RADIATION) THEN
                    ! TWO_DX_KAPPA_S of wall.f90; the composition is fixed for the lines on the device.
                    ! Per-line noding (LAYER_INDEX_H, RDX_H), so that VARIABLE_THICKNESS lines are right as well.
                    INT_RAD_H(IL) = 1
                    DO I=1,NWP
                        LI = LAYER_INDEX_H(BASE+I)
                        IF (SF%KAPPA_S(LI)<0._EB) THEN
                            VOLSUM = 0._EB
                            KAPSUM = 0._EB
                            DO J=1,NMATL
                                IF (ONE_D%MATL_COMP(J)%RHO(I)<=TWENTY_EPSILON_EB) CYCLE
                                RHO_ADJ = MATERIAL(ONE_D%MATL_INDEX(J))%RHO_S*SF%DENSITY_ADJUST_FACTOR(LI,J)
                                VOLSUM = VOLSUM + ONE_D%MATL_COMP(J)%RHO(I)/RHO_ADJ
                                KAPSUM = KAPSUM + ONE_D%MATL_COMP(J)%RHO(I)*MATERIAL(ONE_D%MATL_INDEX(J))%KAPPA_S/RHO_ADJ
                            ENDDO
                            IF (VOLSUM>0._EB) TWO_DX_KAPPA_H(BASE+I) = 2._EB*KAPSUM/(RDX_H(BASE+I)*VOLSUM)
                        ELSE
                            TWO_DX_KAPPA_H(BASE+I) = 2._EB*SF%KAPPA_S(LI)/RDX_H(BASE+I)
                        ENDIF
                    ENDDO
                ENDIF
                DO I=1,NMATL
                    GLOBAL_MATL = ONE_D%MATL_INDEX(I)
                    LOCAL_MATL = 0
                    DO J=1,GM%HT1D_N_UNIQUE_MATL
                        IF (UNIQUE_MATL_H(J)==GLOBAL_MATL) THEN
                            LOCAL_MATL = J
                            EXIT
                        ENDIF
                    ENDDO
                    IF (LOCAL_MATL==0) THEN
                        GM%HT1D_N_UNIQUE_MATL = GM%HT1D_N_UNIQUE_MATL + 1
                        LOCAL_MATL = GM%HT1D_N_UNIQUE_MATL
                        UNIQUE_MATL_H(LOCAL_MATL) = GLOBAL_MATL
                    ENDIF
                    MATL_INDEX_H(MATL_OFFSET_H(IL)+I-1) = LOCAL_MATL
                    MATL_GLOBAL_INDEX_H(MATL_OFFSET_H(IL)+I-1) = GLOBAL_MATL
                    MATL_COMP_OFFSET_H(MATL_OFFSET_H(IL)+I-1) = COMP_TOTAL + 1
                    MATL_COMP_RHO_H(COMP_TOTAL+1:COMP_TOTAL+NWP+2) = ONE_D%MATL_COMP(I)%RHO(0:NWP+1)
                    COMP_TOTAL = COMP_TOTAL + NWP + 2
                ENDDO
                DO NL=1,ONE_D%N_LAYERS
                    DO I=1,NMATL
                        DENSITY_ADJUST_H(MATL_LAYER_OFFSET_H(IL)+(NL-1)*NMATL+I-1) = SF%DENSITY_ADJUST_FACTOR(NL,I)
                    ENDDO
                ENDDO
                DO I=0,NWP+1
                    NL = MAX(1,MIN(ONE_D%N_LAYERS,LAYER_INDEX_H(BASE+I)))
                    PACKING_RATIO_H(BASE+I) = SF%PACKING_RATIO(NL)
                ENDDO

                NODE_TOTAL = NODE_TOTAL + NWP + 2
                MATL_TOTAL = MATL_TOTAL + NMATL
                MATL_LAYER_TOTAL = MATL_LAYER_TOTAL + NMATL*ONE_D%N_LAYERS
            ENDDO

            ! Resolve same-mesh backside lines after all WALL-to-line entries
            ! have been populated. A zero value means that the backside is
            ! remote, absent, or not eligible for this GPU HT1D subset.
            DO IL=1,GM%HT1D_N_LINES
                IF (GM%HT1D_BACK_REMOTE_H(IL)/=0) CYCLE
                IF (GM%HT1D_BACK_INDEX_H(IL)<1 .OR. GM%HT1D_BACK_INDEX_H(IL)>SIZE(GM%HT1D_WALL_TO_LINE_H)) CYCLE
                GM%HT1D_BACK_LINE_H(IL) = GM%HT1D_WALL_TO_LINE_H(GM%HT1D_BACK_INDEX_H(IL))
            ENDDO

            ! Front and exposed-back boundary flags come from their respective SURFs.
            DO IL=1,GM%HT1D_N_LINES
                GM%HT1D_DIRICHLET_FRONT_H(IL) = 0
                GM%HT1D_DIRICHLET_BACK_H(IL) = 0
                IF (GM%HT1D_BACKING_H(IL)==VOID) THEN
                    WC => M%WALL(WALL_INDEX_H(IL))
                    SF => SURFACE(WC%SURF_INDEX)
                    GM%HT1D_DIRICHLET_BACK_H(IL) = MERGE(1,0,SF%DIRICHLET_BACK)
                ELSEIF (GM%HT1D_BACKING_H(IL)==EXPOSED .AND. GM%HT1D_BACK_LINE_H(IL)>0) THEN
                    WC => M%WALL(WALL_INDEX_H(GM%HT1D_BACK_LINE_H(IL)))
                    SF => SURFACE(WC%SURF_INDEX)
                    GM%HT1D_DIRICHLET_BACK_H(IL) = MERGE(1,0,SF%DIRICHLET_FRONT)
                ELSEIF (GM%HT1D_BACKING_H(IL)==EXPOSED .AND. GM%HT1D_BACK_REMOTE_H(IL)/=0 .AND. &
                    GM%HT1D_BACK_MESH_H(IL)>=1 .AND. GM%HT1D_BACK_MESH_H(IL)<=NMESHES) THEN
                    IF (ALLOCATED(MESHES(GM%HT1D_BACK_MESH_H(IL))%WALL) .AND. &
                        GM%HT1D_BACK_INDEX_H(IL)>=1 .AND. GM%HT1D_BACK_INDEX_H(IL)<= &
                        MESHES(GM%HT1D_BACK_MESH_H(IL))%N_EXTERNAL_WALL_CELLS + &
                        MESHES(GM%HT1D_BACK_MESH_H(IL))%N_INTERNAL_WALL_CELLS) THEN
                        WC => MESHES(GM%HT1D_BACK_MESH_H(IL))%WALL(GM%HT1D_BACK_INDEX_H(IL))
                        IF (WC%SURF_INDEX>=1 .AND. WC%SURF_INDEX<=SIZE(SURFACE)) THEN
                            SF => SURFACE(WC%SURF_INDEX)
                            GM%HT1D_DIRICHLET_BACK_H(IL) = MERGE(1,0,SF%DIRICHLET_FRONT)
                        ENDIF
                    ENDIF
                ENDIF
            ENDDO

            ! A remote BACK_INDEX is a WALL index in BACK_MESH. Map it to the
            ! existing receive-list slot once; the time-dependent values are
            ! copied by the exchange layer before the solve.
            DO IL=1,GM%HT1D_N_LINES
                IF (GM%HT1D_BACK_REMOTE_H(IL)==0) CYCLE
                IF (GM%HT1D_BACK_MESH_H(IL)<1 .OR. GM%HT1D_BACK_MESH_H(IL)>NMESHES) CYCLE
                IF (PROCESS(GM%HT1D_BACK_MESH_H(IL))==MY_RANK) THEN
                    IF (.NOT.ALLOCATED(MESHES(GM%HT1D_BACK_MESH_H(IL))%WALL)) CYCLE
                    IF (GM%HT1D_BACK_INDEX_H(IL)<1 .OR. GM%HT1D_BACK_INDEX_H(IL)> &
                        MESHES(GM%HT1D_BACK_MESH_H(IL))%N_EXTERNAL_WALL_CELLS + &
                        MESHES(GM%HT1D_BACK_MESH_H(IL))%N_INTERNAL_WALL_CELLS) CYCLE
                    GM%HT1D_BACKSIDE_VALID_H(IL) = 1
                    CYCLE
                ENDIF
                IF (.NOT.ALLOCATED(M%OMESH)) CYCLE
                IF (.NOT.ALLOCATED(M%OMESH(GM%HT1D_BACK_MESH_H(IL))%WALL_RECV_BUFFER%ITEM_INDEX)) CYCLE
                DO SLOT=1,M%OMESH(GM%HT1D_BACK_MESH_H(IL))%WALL_RECV_BUFFER%N_ITEMS
                    IF (M%OMESH(GM%HT1D_BACK_MESH_H(IL))%WALL_RECV_BUFFER%ITEM_INDEX(SLOT)==GM%HT1D_BACK_INDEX_H(IL)) THEN
                        GM%HT1D_BACK_SLOT_H(IL) = SLOT
                        IF (ALLOCATED(GPU_MESHES(NM)%OMESH(GM%HT1D_BACK_MESH_H(IL))%HT1D_RECV_PKG_D)) &
                            GM%HT1D_BACKSIDE_VALID_H(IL) = 1
                        EXIT
                    ENDIF
                ENDDO
            ENDDO

            ALLOCATE(MATL_RHO_S_H(1:GM%HT1D_N_UNIQUE_MATL))
            ALLOCATE(MATL_K_S_H(0:I_MAX_TEMP,1:GM%HT1D_N_UNIQUE_MATL))
            ALLOCATE(MATL_C_S_H(0:I_MAX_TEMP,1:GM%HT1D_N_UNIQUE_MATL))
            DO I=1,GM%HT1D_N_UNIQUE_MATL
                GLOBAL_MATL = UNIQUE_MATL_H(I)
                MATL_RHO_S_H(I) = MATERIAL(GLOBAL_MATL)%RHO_S
                MATL_K_S_H(:,I) = MATERIAL(GLOBAL_MATL)%K_S(0:I_MAX_TEMP)
                MATL_C_S_H(:,I) = MATERIAL(GLOBAL_MATL)%C_S(0:I_MAX_TEMP)
            ENDDO

            ! Cache node properties when every material table is temperature independent.
            STATIC_TABLE = .TRUE.
            DO I=1,GM%HT1D_N_UNIQUE_MATL
                DO ITMP=1,I_MAX_TEMP
                    IF (MATL_K_S_H(ITMP,I)/=MATL_K_S_H(0,I)) STATIC_TABLE = .FALSE.
                    IF (MATL_C_S_H(ITMP,I)/=MATL_C_S_H(0,I)) STATIC_TABLE = .FALSE.
                ENDDO
            ENDDO
            GM%HT1D_STATIC_MATERIALS = STATIC_TABLE

            ALLOCATE(GM%HT1D_WALL_INDEX_D(1:GM%HT1D_N_LINES),GM%HT1D_OD_INDEX_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_B1_INDEX_D(1:GM%HT1D_N_LINES),GM%HT1D_BC_INDEX_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_SURF_INDEX_D(1:GM%HT1D_N_LINES),GM%HT1D_IEC_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_IOR_D(1:GM%HT1D_N_LINES),GM%HT1D_BACK_INDEX_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACK_MESH_D(1:GM%HT1D_N_LINES),GM%HT1D_BACK_LINE_D(1:GM%HT1D_N_LINES), &
                GM%HT1D_BACK_REMOTE_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACK_SLOT_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_BACKSIDE_VALID_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_NODE_OFFSET_D(1:GM%HT1D_N_LINES),GM%HT1D_NWP_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_COEFF_VALID_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_MATL_VALID_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_MATL_OFFSET_D(1:GM%HT1D_N_LINES),GM%HT1D_N_MATL_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_LAYER_INDEX_D(1:GM%HT1D_N_NODES),GM%HT1D_MATL_INDEX_D(1:GM%HT1D_N_MATL_TOTAL))
            ALLOCATE(GM%HT1D_MATL_GLOBAL_INDEX_D(1:GM%HT1D_N_MATL_TOTAL),GM%HT1D_MATL_COMP_OFFSET_D(1:GM%HT1D_N_MATL_TOTAL))
            ALLOCATE(GM%HT1D_MATL_LAYER_OFFSET_D(1:GM%HT1D_N_LINES),GM%HT1D_N_LAYERS_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_X_D(1:GM%HT1D_N_NODES),GM%HT1D_DX_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_RDX_D(1:GM%HT1D_N_NODES),GM%HT1D_RDXN_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_DX_WGT_D(1:GM%HT1D_N_NODES),GM%HT1D_TMP_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_MATL_COMP_RHO_D(1:GM%HT1D_N_MATL_COMP_VALUES),GM%HT1D_DENSITY_ADJUST_D(1:GM%HT1D_N_MATL_LAYER_VALUES))
            ALLOCATE(GM%HT1D_PACKING_RATIO_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_MATL_RHO_S_D(1:GM%HT1D_N_UNIQUE_MATL))
            ALLOCATE(GM%HT1D_MATL_K_S_D(0:I_MAX_TEMP,1:GM%HT1D_N_UNIQUE_MATL))
            ALLOCATE(GM%HT1D_MATL_C_S_D(0:I_MAX_TEMP,1:GM%HT1D_N_UNIQUE_MATL))
            ALLOCATE(GM%HT1D_K_NODE_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_K_S_D(1:GM%HT1D_N_NODES),GM%HT1D_RHO_C_S_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_Q_S_D(1:GM%HT1D_N_NODES),GM%HT1D_Q_BASE_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_AAS_D(1:GM%HT1D_N_NODES),GM%HT1D_BBS_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_DDS_D(1:GM%HT1D_N_NODES),GM%HT1D_CCS_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_DDT_D(1:GM%HT1D_N_NODES))
            ALLOCATE(GM%HT1D_RFACF2_D(1:GM%HT1D_N_LINES),GM%HT1D_QDXKF_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_RFACB2_D(1:GM%HT1D_N_LINES),GM%HT1D_QDXKB_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_DT_SUB_D(1:GM%HT1D_N_LINES),GM%HT1D_DT_FO_D(1:GM%HT1D_N_LINES), &
                GM%HT1D_DXF_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_DXB_D(1:GM%HT1D_N_LINES),GM%HT1D_HTCF_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TIME_STEP_FACTOR_D(1:GM%HT1D_N_LINES),GM%HT1D_DELTA_TMP_MAX_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_HTCB_D(1:GM%HT1D_N_LINES),GM%HT1D_TMP_G_F_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TMP_G_B_D(1:GM%HT1D_N_LINES),GM%HT1D_TMP_F_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TMP_B_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_H_FIXED_B_D(GM%HT1D_N_LINES),GM%HT1D_TMP_G_BACK_D(GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_RAMP_H_FIXED_B_D(GM%HT1D_N_LINES),GM%HT1D_RAMP_TMP_G_BACK_D(GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_DIR_BACK_FIX_D(GM%HT1D_N_LINES),GM%HT1D_RAMP_TB_D(GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TMP_BACK_D(GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_Q_LIQUID_F_D(1:GM%HT1D_N_LINES),GM%HT1D_Q_LIQUID_B_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_T_BC_SUB_D(1:GM%HT1D_N_LINES),GM%HT1D_Q_CON_ACCUM_D(1:GM%HT1D_N_LINES), &
                GM%HT1D_Q_RAD_ACCUM_D(1:GM%HT1D_N_LINES),GM%HT1D_LINE_ACTIVE_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_Q_RAD_IN_F_D(1:GM%HT1D_N_LINES),GM%HT1D_Q_RAD_IN_B_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_EMISSIVITY_F_D(1:GM%HT1D_N_LINES),GM%HT1D_EMISSIVITY_B_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_RAD_FRONT_D(1:GM%HT1D_N_LINES),GM%HT1D_RAD_BACK_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_DIRICHLET_FRONT_D(1:GM%HT1D_N_LINES),GM%HT1D_DIRICHLET_BACK_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_INT_RAD_D(1:GM%HT1D_N_LINES),GM%HT1D_ACTIVE_COUNT_D(1))
            ALLOCATE(GM%HT1D_Q_RAD_OUT_OLD_D(1:GM%HT1D_N_LINES),GM%HT1D_Q_RAD_OUT_SUB_D(1:GM%HT1D_N_LINES))
            ALLOCATE(GM%HT1D_TWO_DX_KAPPA_D(1:GM%HT1D_N_NODES),GM%HT1D_Q_IR_D(1:GM%HT1D_N_NODES))

            ! Transfer the fixed line maps and initial state to the device.
            GM%HT1D_WALL_INDEX_D = WALL_INDEX_H
            GM%HT1D_OD_INDEX_D = OD_INDEX_H
            GM%HT1D_B1_INDEX_D = B1_INDEX_H
            GM%HT1D_BC_INDEX_D = BC_INDEX_H
            GM%HT1D_SURF_INDEX_D = SURF_INDEX_H
            GM%HT1D_IEC_D = IEC_H
            GM%HT1D_IOR_D = IOR_H
            GM%HT1D_BACK_INDEX_D = BACK_INDEX_H
            GM%HT1D_BACK_MESH_D = BACK_MESH_H
            GM%HT1D_BACK_LINE_D = GM%HT1D_BACK_LINE_H
            GM%HT1D_BACK_REMOTE_D = GM%HT1D_BACK_REMOTE_H
            GM%HT1D_BACK_SLOT_D = GM%HT1D_BACK_SLOT_H
            GM%HT1D_BACKSIDE_VALID_D = GM%HT1D_BACKSIDE_VALID_H
            GM%HT1D_BACKING_D = GM%HT1D_BACKING_H
            GM%HT1D_NODE_OFFSET_D = NODE_OFFSET_H
            GM%HT1D_NWP_D = NWP_H
            GM%HT1D_DXF_D = GM%HT1D_DXF_H
            GM%HT1D_DXB_D = GM%HT1D_DXB_H
            GM%HT1D_TIME_STEP_FACTOR_D = TIME_STEP_FACTOR_H
            GM%HT1D_DELTA_TMP_MAX_D = DELTA_TMP_MAX_H
            GM%HT1D_RAD_FRONT_H = 0
            GM%HT1D_RAD_BACK_H = 0
            GM%HT1D_COEFF_VALID_D = 0
            GM%HT1D_MATL_VALID_D = 0
            GM%HT1D_MATL_OFFSET_D = MATL_OFFSET_H
            GM%HT1D_N_MATL_D = N_MATL_H
            GM%HT1D_LAYER_INDEX_D = LAYER_INDEX_H
            GM%HT1D_MATL_INDEX_D = MATL_INDEX_H
            GM%HT1D_MATL_GLOBAL_INDEX_D = MATL_GLOBAL_INDEX_H
            GM%HT1D_MATL_COMP_OFFSET_D = MATL_COMP_OFFSET_H
            GM%HT1D_MATL_LAYER_OFFSET_D = MATL_LAYER_OFFSET_H
            GM%HT1D_N_LAYERS_D = N_LAYERS_H
            GM%HT1D_X_D = X_H
            GM%HT1D_DX_D = DX_H
            GM%HT1D_RDX_D = RDX_H
            GM%HT1D_RDXN_D = RDXN_H
            GM%HT1D_DX_WGT_D = DX_WGT_H
            GM%HT1D_TMP_D = TMP_H
            GM%HT1D_MATL_COMP_RHO_D = MATL_COMP_RHO_H
            GM%HT1D_DENSITY_ADJUST_D = DENSITY_ADJUST_H
            GM%HT1D_PACKING_RATIO_D = PACKING_RATIO_H
            GM%HT1D_MATL_RHO_S_D = MATL_RHO_S_H
            GM%HT1D_MATL_K_S_D = MATL_K_S_H
            GM%HT1D_MATL_C_S_D = MATL_C_S_H
            GM%HT1D_K_NODE_D = 0._EB
            GM%HT1D_TMP_H = TMP_H
            GM%HT1D_Q_S_H = 0._EB
            DO IL=1,GM%HT1D_N_LINES
                BASE = GM%HT1D_NODE_OFFSET_H(IL)
                NWP = GM%HT1D_NWP_H(IL)
                GM%HT1D_TMP_B_H(IL) = 0.5_EB*(TMP_H(BASE+NWP)+TMP_H(BASE+NWP+1))
            ENDDO
            DO IL=1,GM%HT1D_N_LINES
                IW = WALL_INDEX_H(IL)
                WC => M%WALL(IW)
                ONE_D => M%BOUNDARY_ONE_D(WC%OD_INDEX)
                BASE = GM%HT1D_NODE_OFFSET_H(IL)
                DO I=1,GM%HT1D_NWP_H(IL)
                    NL = MAX(1,MIN(ONE_D%N_LAYERS,LAYER_INDEX_H(BASE+I)))
                    IF (ALLOCATED(ONE_D%HEAT_SOURCE)) GM%HT1D_Q_S_H(BASE+I) = ONE_D%HEAT_SOURCE(NL)
                ENDDO
            ENDDO
            GM%HT1D_K_S_D = 0._EB
            GM%HT1D_RHO_C_S_D = 0._EB
            GM%HT1D_Q_S_D = GM%HT1D_Q_S_H
            GM%HT1D_Q_BASE_D = GM%HT1D_Q_S_H
            GM%HT1D_AAS_D = 0._EB
            GM%HT1D_BBS_D = 0._EB
            GM%HT1D_DDS_D = 0._EB
            GM%HT1D_CCS_D = 0._EB
            GM%HT1D_DDT_D = 0._EB
            GM%HT1D_RFACF2_D = 0._EB
            GM%HT1D_QDXKF_D = 0._EB
            GM%HT1D_RFACB2_D = 0._EB
            GM%HT1D_QDXKB_D = 0._EB
            GM%HT1D_DT_FO_D = 0._EB
            GM%HT1D_T_BC_SUB_D = 0._EB
            GM%HT1D_Q_CON_ACCUM_D = 0._EB
            GM%HT1D_Q_RAD_ACCUM_D = 0._EB
            GM%HT1D_LINE_ACTIVE_D = 0
            ! Per-line boundary values filled by HT1D_LOAD_BOUNDARY_GPU; Q_LIQUID_F/B by HT1D_SET_LIQUID_GPU (droplets on
            ! the surface) before each WALL_BC_GPU of the corrector. Start all of them from zero, since reused device memory is not zeroed (rebuild after an
            ! obstruction was created or removed).
            GM%HT1D_Q_LIQUID_F_D = 0._EB
            GM%HT1D_Q_LIQUID_B_D = 0._EB
            GM%HT1D_HTCF_D = 0._EB
            GM%HT1D_HTCB_D = 0._EB
            GM%HT1D_TMP_G_F_D = 0._EB
            GM%HT1D_TMP_G_B_D = 0._EB
            GM%HT1D_TMP_F_D = 0._EB
            GM%HT1D_Q_RAD_IN_F_D = 0._EB
            GM%HT1D_Q_RAD_IN_B_D = 0._EB
            GM%HT1D_EMISSIVITY_F_D = 0._EB
            GM%HT1D_DT_SUB_D = 0._EB
            GM%HT1D_RAD_FRONT_D = 0
            GM%HT1D_RAD_BACK_D = 0
